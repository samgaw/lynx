defmodule Lynx.Rustler.EncoderDisposalTest do
  use ExUnit.Case, async: true
  alias Lynx.Rust.{LLBC, VTables}
  alias Lynx.Rustler.EncoderDisposal

  setup do
    document =
      File.read!(Path.expand("../../fixtures/rustler/string_vtable.json", __DIR__))
      |> JSON.decode!()

    translated = document["translated"]
    [global] = VTables.foreign_globals(translated)
    {tables, _, _} = VTables.audit!([global], [], translated, LLBC.type_references!(document))
    table = tables[global["def_id"]]
    info = table["lynx_vtable"]

    report = %{
      "crate" => "fixture",
      "trait_decls" => [],
      "functions" => [],
      "trait_impls" => [
        %{
          "def_id" => info.impl,
          "impl_trait_def_id" => info.trait,
          "impl_trait_is_builtin" => true,
          "impl_trait_rust_name" => "rustler::types::Encoder",
          "rust_name" => "rustler::types::Encoder<String>",
          "lean_name" => "fixture.StringEncoder",
          "lean_file" => "Funs.lean"
        }
      ]
    }

    %{audit: %{constants: tables}, report: report}
  end

  @tag :tmp_dir
  test "adds a checked disposal capability without changing the actual encoder", ctx do
    path = Path.join(ctx.tmp_dir, "Funs.lean")
    source = generated("Lynx.Rustler.Encoding.string")
    File.write!(path, source)

    assert [%{dictionary: "fixture.StringEncoder", kind: :sdk_string}] =
             EncoderDisposal.install!(ctx.audit, ctx.report, ctx.tmp_dir)

    changed = File.read!(path)
    assert String.replace(changed, ",\n  dispose := fun _ => RustM.ok ()", "") == source
  end

  @tag :tmp_dir
  test "rejects another well-typed encoder for the same logical String representation", ctx do
    # SDK Atom and String share a Lean representation but encode differently.
    File.write!(Path.join(ctx.tmp_dir, "Funs.lean"), generated("Lynx.Rustler.Encoding.atom"))

    assert_raise ArgumentError, ~r/cannot replace the audited encode method/, fn ->
      EncoderDisposal.install!(ctx.audit, ctx.report, ctx.tmp_dir)
    end
  end

  @tag :tmp_dir
  test "does not certify unknown dictionaries or overwrite user source", ctx do
    path = Path.join(ctx.tmp_dir, "Funs.lean")
    source = generated("Lynx.Rustler.Encoding.string")
    File.write!(path, source)
    assert EncoderDisposal.install!(%{constants: %{}}, ctx.report, ctx.tmp_dir) == []
    assert File.read!(path) == source
    File.write!(path, "module\npublic section\n")

    assert_raise ArgumentError, ~r/refusing to decorate a user Encoder/, fn ->
      EncoderDisposal.install!(ctx.audit, ctx.report, ctx.tmp_dir)
    end
  end

  defp generated(method),
    do:
      "-- THIS FILE WAS AUTOMATICALLY GENERATED BY AENEAS\nmodule\nnamespace fixture\ndef StringEncoder : Lynx.Rustler.Encoder String := {\n  encode := #{method}\n}\nend fixture\n"
end
