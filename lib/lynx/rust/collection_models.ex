defmodule Lynx.Rust.CollectionModels do
  @moduledoc false
  alias Lynx.Rust.CallModels

  def resolve(function, translated, refs) do
    owned(function, translated, refs) || views(function, translated, refs) ||
      trait_view(function, translated, refs)
  end

  defp owned(function, translated, refs) do
    with %{
           "body" => "Opaque",
           "src" => "Normal",
           "signature" => %{"is_unsafe" => false, "is_variadic" => false, "abi" => "Rust"} = sig,
           "generics" => params,
           "item_meta" => %{
             "name" => [
               %{"Ident" => ["alloc", 0]},
               %{"Ident" => ["vec", 0]},
               %{
                 "Impl" => %{
                   "Ty" => %{
                     "kind" => "InherentImplBlock",
                     "params" => parent_params,
                     "skip_binder" => parent
                   }
                 }
               },
               %{"Ident" => [method, 0]}
             ]
           }
         } <- function,
         true <- method in ~w(new len push),
         %{"Adt" => %{"builtin" => nil, "id" => id, "generics" => args}} = vector <-
           CallModels.expand(parent, refs) |> free(),
         true <- args == arguments([type_var(0)]),
         type when not is_nil(type) <-
           Enum.find(translated["type_decls"], &(&1 && &1["def_id"] == id)),
         true <-
           type["item_meta"]["name"] == path(~w(alloc vec Vec)) and
             type_parameters?(type["generics"]),
         true <-
           owned_params?(
             method,
             CallModels.expand(params, refs),
             CallModels.expand(parent_params, refs),
             translated,
             refs
           ),
         true <-
           owned_signature?(
             method,
             CallModels.expand(sig["inputs"], refs),
             CallModels.expand(sig["output"], refs),
             vector
           ) do
      model = %{
        rust_name: "alloc::vec::{alloc::vec::Vec<@T>}::#{method}",
        lean: "Aeneas.Std.alloc.vec.Vec.#{method}",
        builtin: true,
        vec_owned_method: method,
        can_fail: method == "push",
        lift: method == "push",
        native_cutoff_only: method == "push",
        label:
          "Aeneas logical Vec::#{method} model; push verifies at most 262144 scalar elements; exceeding this is verification exhaustion, not Rust rejection; capacity observation, allocation failures and native allocator correctness unverified"
      }

      if method == "new", do: model, else: Map.put(model, :keep_params, [true, false])
    else
      _ -> nil
    end
  end

  def scope(audit, prefix) do
    %{
      audit
      | external_calls:
          Map.new(audit.external_calls, fn {id, model} ->
            if model[:vec_owned_method] == "push",
              do: {id, %{model | lean: prefix <> ".VectorModel.push"}},
              else: {id, model}
          end)
    }
  end

  def install!(audit, translation, output, prefix) do
    if Enum.any?(audit.external_calls, fn {_, model} -> model[:vec_owned_method] == "push" end) do
      module = prefix <> ".VectorModel"
      path = Path.join(output, String.replace(module, ".", "/") <> ".lean")

      case File.read(path) do
        {:ok, "-- Generated by Lynx:" <> _} -> :ok
        {:error, :enoent} -> :ok
        _ -> raise ArgumentError, "refusing to overwrite a user Lean module: #{path}"
      end

      File.mkdir_p!(Path.dirname(path))

      File.write!(path, """
      -- Generated by Lynx: bounded logical scalar vectors.
      module
      public import Aeneas
      public section
      open Aeneas Aeneas.Std
      namespace #{module}
      @[expose] def push {α : Type} (values : alloc.vec.Vec α) (value : α) : RustM (alloc.vec.Vec α) :=
        if values.val.length < 262144 then alloc.vec.Vec.push values value else RustM.fail .undef
      theorem push_within {α : Type} (values : alloc.vec.Vec α) (value : α)
          (bounded : values.val.length < 262144) : push values value = alloc.vec.Vec.push values value := by
        simp only [push, if_pos bounded]
      theorem push_cutoff {α : Type} (values : alloc.vec.Vec α) (value : α)
          (outside : ¬values.val.length < 262144) : push values value = RustM.fail .undef := by
        simp only [push, if_neg outside]
      @[cbv_eval] theorem push_eq {α : Type} (values : alloc.vec.Vec α) (value : α) :
          push values value =
            if bounded : values.val.length < 262144 then
              RustM.ok (alloc.vec.Vec.from (values.val ++ [value]) (by
                simp only [List.length_append, List.length_singleton]
                scalar_tac))
            else RustM.fail .undef := by
        split
        · rename_i bounded
          have capacity : values.val.length + 1 ≤ U32.max := by scalar_tac
          simp [push, alloc.vec.Vec.push, bounded, capacity]
        · rename_i outside
          exact push_cutoff values value outside
      theorem push_outcome {α : Type} (values : alloc.vec.Vec α) (value : α) :
          (∃ next, push values value = RustM.ok next) ∨
            push values value = RustM.fail .undef := by
        by_cases bounded : values.val.length < 262144
        · have capacity : values.val.length + 1 ≤ U32.max := by scalar_tac
          left
          simp [push, alloc.vec.Vec.push, bounded, capacity]
        · exact Or.inr (push_cutoff values value bounded)
      end #{module}
      """)

      functions = Path.join(output, String.replace(prefix, ".", "/") <> "/Funs.lean")
      source = File.read!(functions)

      if Enum.any?(
           Enum.flat_map(~w(functions globals types), &Map.get(translation, &1, [])),
           fn function ->
             name = function["lean_name"]

             is_binary(name) and
               (name == "alloc.vec.Vec.push" or String.ends_with?(name, ".alloc.vec.Vec.push"))
           end
         ),
         do: raise(ArgumentError, "ambiguous application Vec::push name for bounded model")

      {source, count} =
        Lynx.Rust.LeanIdentifiers.replace(
          source,
          [
            "_root_.Aeneas.Std.alloc.vec.Vec.push",
            "Aeneas.Std.alloc.vec.Vec.push",
            "alloc.vec.Vec.push"
          ],
          "_root_." <> module <> ".push"
        )

      if count == 0, do: raise(ArgumentError, "missing Aeneas Vec::push call for bounded model")

      source =
        String.replace(
          source,
          "public import Aeneas\n",
          "public import Aeneas\npublic import #{module}\n",
          global: false
        )

      File.write!(functions, source)
      [module]
    else
      []
    end
  end

  def audit(functions, models, translated, refs) do
    Enum.reduce_while(functions, :ok, fn function, :ok ->
      try do
        audit_node(function["body"], models, translated, refs)
        {:cont, :ok}
      rescue
        error in ArgumentError -> {:halt, {:error, function, Exception.message(error)}}
      end
    end)
  end

  defp audit_node(
         %{"Regular" => %{"kind" => %{"Fun" => id}, "generics" => args}} = node,
         models,
         translated,
         refs
       ) do
    if method = get_in(models, [id, :vec_owned_method]) do
      types = CallModels.expand(args["types"], refs)

      valid =
        case {method, types} do
          {"new", [element]} ->
            Lynx.Rust.DropModels.primitive_scalar?(element)

          {_,
           [element, %{"Adt" => %{"id" => allocator, "builtin" => nil, "generics" => alloc_args}}]} ->
            Lynx.Rust.DropModels.primitive_scalar?(element) and alloc_args == arguments([]) and
              Enum.any?(translated["type_decls"], fn type ->
                type != nil and type["def_id"] == allocator and
                  type["item_meta"]["name"] == path(~w(alloc alloc Global)) and
                  type["generics"]["types"] == [] and type["generics"]["regions"] == [] and
                  type["generics"]["trait_clauses"] == [] and
                  type["generics"]["const_generics"] == [] and
                  type["generics"]["outlives"] == [] and
                  type["generics"]["trait_type_constraints"] == []
              end)

          _ ->
            false
        end

      unless valid,
        do:
          raise(
            ArgumentError,
            "unsupported Vec::#{method}: only primitive scalar elements and the standard Global allocator are admitted"
          )
    end

    Enum.each(Map.values(node), &audit_node(&1, models, translated, refs))
  end

  defp audit_node(node, models, translated, refs) when is_map(node),
    do: Enum.each(Map.values(node), &audit_node(&1, models, translated, refs))

  defp audit_node(node, models, translated, refs) when is_list(node),
    do: Enum.each(node, &audit_node(&1, models, translated, refs))

  defp audit_node(_, _, _, _), do: :ok

  defp owned_signature?("new", [], output, vector), do: output == vector

  defp owned_signature?("len", [input], output, vector),
    do:
      input == reference(vector, "Shared") and
        output == %{"Scalar" => %{"Integer" => %{"Unsigned" => "Usize"}}}

  defp owned_signature?("push", [input, element], output, vector),
    do:
      input == reference(vector, "Mut") and element == type_var(0) and
        match?(
          %{"Adt" => %{"builtin" => "Tuple", "generics" => args}}
          when args == %{
                 "regions" => [],
                 "types" => [],
                 "const_generics" => [],
                 "trait_refs" => []
               },
          output
        )

  defp owned_signature?(_, _, _, _), do: false

  defp owned_params?("new", params, parent, _translated, _refs),
    do: type_parameters?(params) and type_parameters?(parent)

  defp owned_params?("len", params, parent, _translated, _refs),
    do: parameters?(params, 1) and parameters?(parent, 0)

  defp owned_params?("push", params, parent, translated, refs) do
    with %{"trait_clauses" => [clause]} <- params,
         %{"trait_clauses" => [parent_clause]} <- parent,
         true <-
           parameters?(%{params | "trait_clauses" => []}, 1) and
             parameters?(%{parent | "trait_clauses" => []}, 0),
         %{
           "clause_id" => 0,
           "trait_" => %{
             "regions" => [],
             "outlives" => [],
             "skip_binder" => %{"id" => id, "generics" => args}
           }
         } <- clause,
         %{
           "clause_id" => 0,
           "trait_" => %{
             "regions" => [],
             "outlives" => [],
             "skip_binder" => %{"id" => ^id, "generics" => parent_args}
           }
         } <- parent_clause,
         true <-
           args == arguments([type_var(1)]) and
             parent_args == arguments([%{"TypeVar" => %{"Bound" => [1, 1]}}]),
         true <- Lynx.Rust.DropModels.standard_destruct_trait?(id, translated, refs) do
      true
    else
      _ -> false
    end
  end

  defp views(function, translated, refs) do
    with %{
           "body" => "Opaque",
           "src" => "Normal",
           "signature" => %{"is_unsafe" => false, "is_variadic" => false, "abi" => "Rust"} = sig,
           "generics" => params,
           "item_meta" => %{
             "name" => [
               %{"Ident" => ["alloc", 0]},
               %{"Ident" => ["vec", 0]},
               %{
                 "Impl" => %{
                   "Ty" => %{
                     "kind" => "InherentImplBlock",
                     "params" => parent_params,
                     "skip_binder" => parent
                   }
                 }
               },
               %{"Ident" => [method, 0]}
             ]
           }
         } <- function,
         true <- method in ~w(as_slice as_mut_slice),
         true <- parameters?(CallModels.expand(params, refs), 1),
         true <- parameters?(parent_params, 0),
         %{"Adt" => %{"builtin" => nil, "id" => id, "generics" => args}} = vector <-
           CallModels.expand(parent, refs) |> free(),
         true <- args == arguments([type_var(0)]),
         type when not is_nil(type) <-
           Enum.find(translated["type_decls"], &(&1 && &1["def_id"] == id)),
         true <- type["item_meta"]["name"] == path(~w(alloc vec Vec)),
         true <- type_parameters?(type["generics"]),
         mutability = if(method == "as_mut_slice", do: "Mut", else: "Shared"),
         true <- CallModels.expand(sig["inputs"], refs) == [reference(vector, mutability)],
         true <-
           CallModels.expand(sig["output"], refs) ==
             reference(%{"Slice" => [type_var(0), nil]}, mutability) do
      %{
        rust_name: "alloc::vec::{alloc::vec::Vec<@T>}::#{method}",
        lean:
          "Aeneas.Std.alloc.vec.Vec." <>
            if(method == "as_mut_slice", do: "deref_mut", else: "deref"),
        builtin: false,
        can_fail: false,
        lift: method == "as_mut_slice",
        keep_params: [true, false],
        label:
          "Aeneas Vec slice-view model preserving in-place updates; allocation and capacity are not observed; Rust alloc implementation not verified"
      }
    else
      _ -> nil
    end
  end

  # Vec's standard Deref uses the same logical shared slice as as_slice.
  # Validate the actual trait/method identity; never apply this to user Deref bodies.
  defp trait_view(function, translated, refs) do
    function = CallModels.expand(function, refs)
    ctx = %{translated: translated, refs: refs, traits: %{}}

    with %{
           "body" => "Opaque",
           "src" => %{"TraitImpl" => source},
           "signature" => %{"abi" => "Rust", "is_unsafe" => false, "is_variadic" => false} = sig
         } <- function,
         %{"id" => impl_id} <- source["impl_ref"],
         %{"id" => trait_id} <- source["trait_ref"],
         impl when not is_nil(impl) <- find(translated["trait_impls"], impl_id),
         trait when not is_nil(trait) <- find(translated["trait_decls"], trait_id),
         impl = CallModels.expand(impl, refs),
         trait = CallModels.expand(trait, refs),
         name = path(~w(alloc vec)) ++ [%{"Impl" => %{"Trait" => impl_id}}],
         true <- function["item_meta"]["name"] == name ++ path(~w(deref)),
         true <- impl["item_meta"]["name"] == name,
         true <- impl["src"] == "Normal" and not impl["is_negative"] and not impl["is_unsafe"],
         true <-
           impl["consts"] == [] and impl["types"] == [nil] and impl["implied_trait_refs"] == [],
         true <- parameters?(impl["generics"], 0) and parameters?(function["generics"], 1),
         %{"id" => ^trait_id, "generics" => args} <- impl["impl_trait"],
         [vector, target] <- args["types"],
         true <- args == arguments([vector, target]),
         true <- target == %{"Slice" => [type_var(0), nil]},
         %{"Adt" => %{"id" => vec_id, "builtin" => nil, "generics" => vec_args}} <- vector,
         true <- vec_args == arguments([type_var(0)]),
         vector_decl when not is_nil(vector_decl) <- find(translated["type_decls"], vec_id),
         true <- vector_decl["item_meta"]["name"] == path(~w(alloc vec Vec)),
         true <- type_parameters?(vector_decl["generics"]),
         true <- deref_trait?(trait),
         true <- Lynx.Rust.FormatModels.method_identity?(function, impl, trait_id, ctx),
         true <- sig["inputs"] == [reference(vector, "Shared")],
         true <- sig["output"] == reference(target, "Shared") do
      %{
        rust_name: "alloc::vec::{core::ops::deref::Deref<alloc::vec::Vec<@T>, [@T]>}::deref",
        lean: "Aeneas.Std.alloc.vec.Vec.deref",
        builtin: true,
        can_fail: false,
        lift: false,
        keep_params: [true, false],
        label:
          "Standard Vec Deref shared slice-view model; actual compiled trait and method identities validated; Rust alloc implementation, native references and allocator correctness unverified"
      }
    else
      _ -> nil
    end
  end

  defp deref_trait?(trait) do
    r = %{"Var" => %{"Bound" => [0, 0]}}

    with true <- trait["item_meta"]["name"] == path(~w(core ops deref Deref)),
         true <- trait["src"] == "Normal" and trait["is_unsafe"] == false,
         true <-
           trait["consts"] == [] and trait["types"] == [nil] and trait["implied_clauses"] == [],
         true <- parameters?(trait["generics"], 0),
         [%{"kind" => %{"TraitMethod" => [id, 0]}, "params" => p, "skip_binder" => method}] <-
           trait["methods"],
         true <- id == trait["def_id"],
         true <- Enum.map(p["regions"], & &1["index"]) == [0],
         true <- Enum.all?(Map.values(Map.delete(p, "regions")), &(&1 == [])),
         true <- method["name"] == "deref" and method["default"] == nil do
      method["signature"] == %{
        "abi" => "Rust",
        "is_unsafe" => false,
        "is_variadic" => false,
        "inputs" => [%{"Ref" => [r, type_var(0), "Shared"]}],
        "output" => %{"Ref" => [r, type_var(1), "Shared"]}
      }
    else
      _ -> false
    end
  end

  defp find(items, id), do: Enum.find(items, &(&1 && &1["def_id"] == id))

  defp type_parameters?(%{
         "regions" => [],
         "types" => [%{"index" => 0}],
         "const_generics" => [],
         "trait_clauses" => [],
         "trait_type_constraints" => [],
         "outlives" => []
       }),
       do: true

  defp type_parameters?(_), do: false

  defp parameters?(
         %{
           "regions" => regions,
           "types" => [%{"index" => 0}, %{"index" => 1}],
           "const_generics" => [],
           "trait_clauses" => [],
           "trait_type_constraints" => [],
           "outlives" => outlives
         },
         count
       ) do
    case count do
      0 ->
        regions == [] and outlives == []

      1 ->
        match?([%{"index" => 0}], regions) and
          outlives ==
            Enum.map(0..1, fn index ->
              %{
                "regions" => [],
                "outlives" => [],
                "skip_binder" => [%{"Lub" => type_var(index)}, %{"Var" => %{"Free" => 0}}]
              }
            end)
    end
  end

  defp parameters?(_, _), do: false

  defp reference(type, mutability), do: %{"Ref" => [%{"Var" => %{"Free" => 0}}, type, mutability]}

  defp arguments(types),
    do: %{"regions" => [], "types" => types, "const_generics" => [], "trait_refs" => []}

  defp type_var(index), do: %{"TypeVar" => %{"Free" => index}}
  defp path(parts), do: Enum.map(parts, &%{"Ident" => [&1, 0]})
  defp free(%{"Bound" => [0, index]}), do: %{"Free" => index}
  defp free(map) when is_map(map), do: Map.new(map, fn {k, v} -> {k, free(v)} end)
  defp free(list) when is_list(list), do: Enum.map(list, &free/1)
  defp free(value), do: value
end
