defmodule Lynx.Rust.StringModels do
  @moduledoc false
  alias Lynx.Rust.CallModels

  # Rustler text borrows must resolve to rustc's builtin str, not a nominal
  # lookalike or a mutable reference. Native borrow lifetime/layout stays at FFI.
  def borrowed_type?(type, translated, refs) do
    with %{"Ref" => [%{"Var" => %{"Free" => region}}, str, "Shared"]} <-
           CallModels.expand(type, refs),
         true <- is_integer(region) and region >= 0,
         %{"Adt" => %{"id" => id, "builtin" => "Str", "generics" => args}} <- str,
         true <- args == arguments(),
         %{
           "src" => %{"Builtin" => "Str"},
           "kind" => %{"Struct" => [%{"name" => "_0", "ty" => field}]},
           "item_meta" => %{"name" => [%{"Builtin" => ["Str", 0]}]},
           "generics" => params
         } <-
           Enum.find(translated["type_decls"], &(&1 && &1["def_id"] == id)) do
      params == empty_params() and CallModels.expand(field, refs) == bytes()
    else
      _ -> false
    end
  end

  # Str is Aeneas's existing Slice U8 representation. These models preserve its
  # bytes and borrow; they do not prove Rust core's transmute or native layout.
  def resolve(function, translated, refs) do
    with %{
           "body" => "Opaque",
           "src" => "Normal",
           "signature" => %{"is_unsafe" => false, "is_variadic" => false, "abi" => "Rust"} = sig,
           "generics" => params,
           "item_meta" => %{
             "name" => [
               %{"Ident" => ["core", 0]},
               %{"Ident" => ["str", 0]},
               %{
                 "Impl" => %{
                   "Ty" => %{
                     "kind" => "InherentImplBlock",
                     "params" => parent_params,
                     "skip_binder" => parent
                   }
                 }
               },
               %{"Ident" => [method, 0]}
             ]
           }
         } <- function,
         true <- method in ~w(as_bytes len is_empty is_char_boundary),
         true <- parent_params == empty_params(),
         true <- match?([%{"index" => 0}], params["regions"]),
         true <- Map.put(params, "regions", []) == empty_params(),
         %{"Adt" => %{"id" => id, "builtin" => "Str", "generics" => args}} = str <-
           CallModels.expand(parent, refs),
         true <- args == arguments(),
         %{
           "src" => %{"Builtin" => "Str"},
           "generics" => type_params,
           "item_meta" => %{"name" => [%{"Builtin" => ["Str", 0]}]},
           "kind" => %{"Struct" => [%{"name" => "_0", "ty" => field}]}
         } <- Enum.find(translated["type_decls"], &(&1 && &1["def_id"] == id)),
         true <- type_params == empty_params(),
         true <- CallModels.expand(field, refs) == bytes(),
         true <-
           CallModels.expand(sig["inputs"], refs) ==
             if(method == "is_char_boundary",
               do: [reference(str), scalar("Usize")],
               else: [reference(str)]
             ) do
      {output, lean, monadic} =
        case method do
          "as_bytes" -> {reference(bytes()), "id", false}
          "len" -> {scalar("Usize"), "Aeneas.Std.Slice.len", false}
          "is_empty" -> {%{"Scalar" => "Bool"}, "Aeneas.Std.core.slice.Slice.is_empty", true}
          "is_char_boundary" -> {%{"Scalar" => "Bool"}, "StringViews.isCharBoundary", false}
        end

      if CallModels.expand(sig["output"], refs) == output do
        model = %{
          rust_name: "core::str::{str}::" <> method,
          lean: lean,
          builtin: false,
          can_fail: monadic,
          lift: monadic,
          label:
            "Rust shared str byte-view model using Aeneas Slice U8; preserves bytes and byte length; Rust core/native layout not verified"
        }

        if method == "is_char_boundary",
          do:
            model
            |> Map.put(:string_boundary, true)
            |> Map.put(
              :label,
              "Rust shared str UTF-8 boundary model: zero and byte length are boundaries; interior continuation bytes and offsets beyond the end are rejected; Rust core implementation and native layout remain unverified"
            ),
          else: model
      end
    else
      _ -> nil
    end
  end

  def scope(audit, prefix) do
    %{
      audit
      | external_calls:
          Map.new(audit.external_calls, fn {id, model} ->
            if model[:string_boundary],
              do: {id, %{model | lean: prefix <> ".StringViews.isCharBoundary"}},
              else: {id, model}
          end)
    }
  end

  def install!(audit, output, prefix) do
    if Enum.any?(audit.external_calls, fn {_, model} -> model[:string_boundary] end) do
      module = prefix <> ".StringViewsModel"
      path = Path.join(output, String.replace(module, ".", "/") <> ".lean")
      marker = "-- Generated by Lynx: shared string boundary model.\n"

      case File.read(path) do
        {:ok, ^marker <> _} -> :ok
        {:error, :enoent} -> :ok
        _ -> raise ArgumentError, "refusing to overwrite a user string model: #{path}"
      end

      source = """
      #{marker}module
      public import #{prefix}.Types
      public section
      open Aeneas Aeneas.Std
      namespace #{prefix}.StringViews
      @[expose] def isCharBoundary (text : Str) (position : Usize) : Bool :=
        if position.val = 0 then true
        else match text.val[position.val]? with
        | some byte => decide (byte.val < 128 ∨ 192 ≤ byte.val)
        | none => decide (position.val = text.val.length)
      end #{prefix}.StringViews
      """

      File.mkdir_p!(Path.dirname(path))
      File.write!(path, source)
      funs = Path.join(output, String.replace(prefix, ".", "/") <> "/Funs.lean")
      import = "public import " <> prefix <> ".Types"
      contents = File.read!(funs)

      unless String.contains?(contents, import),
        do: raise(ArgumentError, "missing generated string Types import")

      File.write!(funs, String.replace(contents, import, import <> "\npublic import " <> module))
      [module]
    else
      []
    end
  end

  defp reference(type), do: %{"Ref" => [%{"Var" => %{"Free" => 0}}, type, "Shared"]}
  defp bytes, do: %{"Slice" => [scalar("U8"), nil]}
  defp scalar(type), do: %{"Scalar" => %{"Integer" => %{"Unsigned" => type}}}

  defp arguments,
    do: %{"regions" => [], "types" => [], "const_generics" => [], "trait_refs" => []}

  defp empty_params,
    do:
      Map.new(
        ~w(regions types const_generics trait_clauses outlives trait_type_constraints),
        &{&1, []}
      )
end
