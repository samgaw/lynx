defmodule Lynx.Rust.Project do
  @moduledoc false
  @lean Path.expand("../../../Lean", __DIR__)
  @toolchain Path.expand("../../../lean-toolchain", __DIR__)

  def ensure!(project, prefix, tools) do
    unless Regex.match?(~r/^[A-Z][A-Za-z0-9_]*(\.[A-Z][A-Za-z0-9_]*)*$/, prefix),
      do: raise(ArgumentError, "invalid generated Lean module prefix: #{inspect(prefix)}")

    project = Path.expand(project)
    runtime = Path.join(Path.expand(tools), "backends/lean")

    :global.trans({{__MODULE__, project}, self()}, fn ->
      File.mkdir_p!(project)
      canonical = File.read!(@toolchain)
      pin = Path.join(project, "lean-toolchain")

      case File.read(pin) do
        {:ok, ^canonical} ->
          :ok

        {:ok, _} ->
          raise ArgumentError, "Rust proof project must use #{String.trim(canonical)}: #{pin}"

        {:error, :enoent} ->
          File.write!(pin, canonical)

        {:error, reason} ->
          raise File.Error, reason: reason, action: "read Lean toolchain", path: pin
      end

      config = Path.join(project, "lakefile.toml")
      fresh = not (File.regular?(config) or File.regular?(Path.join(project, "lakefile.lean")))

      if fresh do
        unless File.read!(Path.join(runtime, "lean-toolchain")) == canonical,
          do: raise(ArgumentError, "Aeneas runtime and Lynx Lean toolchains differ")

        library = prefix |> String.split(".") |> hd()

        File.write!(config, """
        # Generated by Lynx. Property modules can be added to this Lake library.
        name = "lynx-native-verification"
        defaultTargets = [#{JSON.encode!(library)}]
        [[lean_lib]]
        name = #{JSON.encode!(library)}
        [[require]]
        name = "aeneas"
        path = #{JSON.encode!(runtime)}
        [[require]]
        name = "Lynx"
        path = #{JSON.encode!(@lean)}
        """)

        root = Path.join(project, library <> ".lean")

        unless File.exists?(root),
          do: File.write!(root, "module\n-- Generated by Lynx: native verification project.\n")
      end

      unless File.regular?(Path.join(project, "lake-manifest.json")) do
        build_command!(project, ["update"])
        # Use the existing Mathlib/Aeneas binary cache rather than rebuilding it.
        build_command!(project, ["exe", "cache", "get"])
      end

      project
    end)
  end

  def build!(project, modules), do: build_command!(project, ["build" | Enum.uniq(modules)])

  defp build_command!(project, arguments) do
    {output, status} = System.cmd("lake", arguments, cd: project, stderr_to_stdout: true)

    if status != 0,
      do: raise("native Lean project command failed (#{Enum.join(arguments, " ")}):\n#{output}")

    :ok
  end
end
