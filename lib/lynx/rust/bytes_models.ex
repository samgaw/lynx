defmodule Lynx.Rust.BytesModels do
  @moduledoc false
  alias Lynx.Rust.{CallModels, LLBC}
  @source Path.expand("../../../priv/lean/LynxRustBytes.lean", __DIR__)
  @external_resource @source
  @contents File.read!(@source)

  def resolve(function, translated, refs) do
    with %{
           "body" => "Opaque",
           "src" => "Normal",
           "signature" =>
             %{"is_unsafe" => false, "abi" => "Rust", "is_variadic" => false} = signature,
           "generics" => params
         } <- function,
         true <- parameters?(params),
         type when not is_nil(type) <-
           Enum.find(
             translated["type_decls"],
             &(&1 && &1["item_meta"]["name"] == path(~w(core str error Utf8Error)))
           ),
         true <- error_type?(type, translated, refs) do
      inputs = CallModels.expand(signature["inputs"], refs)
      output = CallModels.expand(signature["output"], refs)
      error = adt(type["def_id"])
      reference = fn t -> %{"Ref" => [%{"Var" => %{"Free" => 0}}, t, "Shared"]} end
      bytes = %{"Slice" => [scalar("U8"), nil]}
      name = function["item_meta"]["name"]

      selected =
        cond do
          name == path(~w(core str converts from_utf8)) and inputs == [reference.(bytes)] and
              result?(output, type["def_id"], translated, refs) ->
            {"core::str::converts::from_utf8", "fromUtf8", true}

          accessor?(name, "valid_up_to", error, refs) and inputs == [reference.(error)] and
              output == scalar("Usize") ->
            {"core::str::error::{core::str::error::Utf8Error}::valid_up_to", "validUpTo", false}

          accessor?(name, "error_len", error, refs) and inputs == [reference.(error)] and
              option?(output, translated, refs, scalar("Usize")) ->
            {"core::str::error::{core::str::error::Utf8Error}::error_len", "errorLen", false}

          true ->
            nil
        end

      if selected do
        {rust, lean, lift} = selected

        %{
          rust_name: rust,
          lean: "Lynx.Rust.Bytes." <> lean,
          builtin: false,
          can_fail: lift,
          lift: lift,
          bytes_error_type: type["def_id"],
          model_hash: Lynx.Rust.Fingerprint.digest(@contents),
          label:
            "Bounded Rust UTF-8 model (4096 bytes); preserves bytes and Utf8Error offsets/lengths; Rust core implementation not verified"
        }
      end
    else
      _ -> nil
    end
  end

  def install!(audit, translation, output, prefix) do
    ids =
      audit.external_calls
      |> Map.values()
      |> Enum.filter(&Map.has_key?(&1, :bytes_error_type))
      |> Enum.map(& &1.bytes_error_type)
      |> Enum.uniq()

    case ids do
      [] ->
        :ok

      [id] ->
        [type] = Enum.filter(translation["types"], &(&1["def_id"] == id))
        module = prefix <> ".BytesModel"
        path = Path.join(output, String.replace(module, ".", "/") <> ".lean")

        case File.read(path) do
          {:ok, "-- Generated by Lynx:" <> _} -> :ok
          {:error, :enoent} -> :ok
          _ -> raise ArgumentError, "refusing to overwrite a user Lean module: #{path}"
        end

        File.mkdir_p!(Path.dirname(path))

        contents =
          @contents
          |> String.replace("__TYPES_MODULE__", prefix <> ".Types")
          |> String.replace("__ERROR_TYPE__", type["lean_name"])
          |> String.replace("__BYTES_NAMESPACE__", prefix <> ".Bytes")

        File.write!(path, contents)
        funs = Path.join(output, String.replace(prefix, ".", "/") <> "/Funs.lean")
        marker = "public import #{prefix}.Types"
        source = File.read!(funs)

        unless String.contains?(source, marker),
          do: raise(ArgumentError, "missing generated Types import")

        File.write!(funs, String.replace(source, marker, marker <> "\npublic import " <> module))
    end
  end

  def scope(audit, prefix) do
    calls =
      Map.new(audit.external_calls, fn {id, model} ->
        if Map.has_key?(model, :bytes_error_type),
          do:
            {id,
             %{
               model
               | lean: String.replace_prefix(model.lean, "Lynx.Rust.Bytes.", prefix <> ".Bytes.")
             }},
          else: {id, model}
      end)

    %{audit | external_calls: calls}
  end

  def modules(audit, prefix) do
    if Enum.any?(Map.values(audit.external_calls), &Map.has_key?(&1, :bytes_error_type)),
      do: [prefix <> ".BytesModel"],
      else: []
  end

  defp path(parts), do: Enum.map(parts, &%{"Ident" => [&1, 0]})
  defp scalar(n), do: %{"Scalar" => %{"Integer" => %{"Unsigned" => n}}}

  defp args(types),
    do: %{"regions" => [], "types" => types, "const_generics" => [], "trait_refs" => []}

  defp adt(id), do: %{"Adt" => %{"id" => id, "builtin" => nil, "generics" => args([])}}

  defp parameters?(%{
         "regions" => [%{"index" => 0}],
         "types" => [],
         "const_generics" => [],
         "trait_clauses" => [],
         "outlives" => [],
         "trait_type_constraints" => []
       }),
       do: true

  defp parameters?(_), do: false

  defp accessor?(
         [
           %{"Ident" => ["core", 0]},
           %{"Ident" => ["str", 0]},
           %{"Ident" => ["error", 0]},
           %{"Impl" => %{"Ty" => %{"skip_binder" => parent}}},
           %{"Ident" => [method, 0]}
         ],
         method,
         error,
         refs
       ),
       do: CallModels.expand(parent, refs) == error

  defp accessor?(_, _, _, _), do: false

  defp error_type?(%{"kind" => %{"Struct" => [a, b]}, "generics" => params}, translated, refs) do
    Enum.all?(Map.values(params), &(&1 == [])) and a["name"] == "valid_up_to" and
      b["name"] == "error_len" and
      CallModels.expand(a["ty"], refs) == scalar("Usize") and
      option?(CallModels.expand(b["ty"], refs), translated, refs)
  end

  defp error_type?(_, _, _), do: false

  defp option?(type, translated, refs, element \\ scalar("U8"))

  defp option?(
         %{"Adt" => %{"id" => id, "builtin" => nil, "generics" => generics}},
         translated,
         refs,
         element
       ) do
    generics == args([element]) and
      Enum.any?(translated["type_decls"], fn type ->
        type && type["def_id"] == id && type["item_meta"]["name"] == path(~w(core option Option)) &&
          match?(
            %{
              "Enum" => [
                %{
                  "id" => 0,
                  "name" => "None",
                  "fields" => [],
                  "discriminant" => %{"Signed" => ["Isize", "0"]}
                },
                %{
                  "id" => 1,
                  "name" => "Some",
                  "fields" => [_],
                  "discriminant" => %{"Signed" => ["Isize", "1"]}
                }
              ]
            },
            type["kind"]
          ) &&
          CallModels.expand(hd(Enum.at(type["kind"]["Enum"], 1)["fields"])["ty"], refs) == %{
            "TypeVar" => %{"Free" => 0}
          }
      end)
  end

  defp option?(_, _, _, _), do: false

  defp result?(
         %{
           "Adt" => %{
             "id" => id,
             "builtin" => nil,
             "generics" => %{"types" => [str, error]} = generics
           }
         },
         error_id,
         translated,
         refs
       ) do
    LLBC.result_type?(id, %{translated: translated, references: refs}) and
      generics == args([str, error]) and error == adt(error_id) and
      str?(str, translated, refs)
  end

  defp result?(_, _, _, _), do: false

  defp str?(str, translated, refs) do
    with %{"Ref" => [%{"Var" => %{"Free" => 0}}, %{"Adt" => %{"id" => id}} = value, "Shared"]} <-
           str,
         true <-
           match?(
             %{
               "Ref" => [
                 %{"Var" => %{"Free" => 0}},
                 %{
                   "Adt" => %{
                     "builtin" => "Str",
                     "generics" => %{
                       "regions" => [],
                       "types" => [],
                       "const_generics" => [],
                       "trait_refs" => []
                     }
                   }
                 },
                 "Shared"
               ]
             },
             str
           ),
         %{
           "kind" => %{"Struct" => [field]},
           "item_meta" => %{"name" => [%{"Builtin" => ["Str", 0]}]}
         } <-
           Enum.find(translated["type_decls"], &(&1 && &1["def_id"] == id)) do
      value["Adt"]["builtin"] == "Str" and
        CallModels.expand(field["ty"], refs) == %{"Slice" => [scalar("U8"), nil]}
    else
      _ -> false
    end
  end
end
