defmodule Lynx.Rust.Runtime do
  @moduledoc false
  @source Path.expand("../../../priv/lean/LynxNativeRuntime.lean", __DIR__)
  @external_resource @source
  @contents File.read!(@source)
  @marker "-- Generated by Lynx: native runtime interpretation.\n"

  @scalar_source Path.expand("../../../priv/lean/LynxRustScalars.lean", __DIR__)
  @external_resource @scalar_source
  @scalar_contents File.read!(@scalar_source)
  @scalar_marker "-- Generated by Lynx: native scalar proofs.\n"

  def fingerprint(:pure), do: Lynx.Rust.Fingerprint.digest(@scalar_contents)

  def fingerprint(:runtime),
    do: Lynx.Rust.Fingerprint.digest(["effectful-calls-v1\n", @contents, @scalar_contents])

  def configuration!(:pure, output, prefix) do
    module = scalars!(output, prefix)
    {"RustM", ["-extra-includes", module], [module]}
  end

  def configuration!(:runtime, output, prefix) do
    module = install!(output, prefix, "NativeRuntime", @marker, @contents)
    scalar_module = scalars!(output, prefix)

    {"Lynx.NativeM",
     [
       "-lean-result-monad",
       "Lynx.NativeM",
       "-preserve-effectful-calls",
       "-loops-no-rec",
       "-extra-includes",
       Enum.join([module, scalar_module], ",")
     ], [module, scalar_module]}
  end

  def configuration!(other, _output, _prefix),
    do: raise(ArgumentError, "unsupported Rust execution model: #{inspect(other)}")

  defp scalars!(output, prefix),
    do: install!(output, prefix, "NativeScalars", @scalar_marker, @scalar_contents)

  defp install!(output, prefix, suffix, marker, contents) do
    module = (prefix |> String.split(".") |> hd()) <> "." <> suffix
    path = Path.join(output, String.replace(module, ".", "/") <> ".lean")

    case File.read(path) do
      {:ok, existing} ->
        unless String.starts_with?(existing, marker),
          do: raise(ArgumentError, "refusing to overwrite a user Lean module: #{path}")

      {:error, :enoent} ->
        :ok

      _ ->
        raise ArgumentError, "refusing to overwrite a user Lean module: #{path}"
    end

    File.mkdir_p!(Path.dirname(path))
    File.write!(path, marker <> contents)
    module
  end
end
