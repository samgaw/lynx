defmodule Lynx.Rust.Runtime do
  @moduledoc false
  @source Path.expand("../../../priv/lean/LynxNativeRuntime.lean", __DIR__)
  @external_resource @source
  @contents File.read!(@source)
  @marker "-- Generated by Lynx: native runtime interpretation.\n"

  @scalar_source Path.expand("../../../priv/lean/LynxRustScalars.lean", __DIR__)
  @external_resource @scalar_source
  @scalar_contents File.read!(@scalar_source)
  @scalar_marker "-- Generated by Lynx: native scalar proofs.\n"

  @try_source Path.expand("../../../priv/lean/LynxRustTry.lean", __DIR__)
  @external_resource @try_source
  @try_contents File.read!(@try_source)
  @try_marker "-- Generated by Lynx: standard Try models.\n"

  @loop_source Path.expand("../../../priv/lean/LynxRustLoops.lean", __DIR__)
  @external_resource @loop_source
  @loop_contents File.read!(@loop_source)
  @loop_marker "-- Generated by Lynx: pure loop monotonicity proofs.\n"

  @usize_literal """
  local macro_rules
    | `($value:num#usize) => `(Aeneas.Std.Usize.ofNat $value (of_decide_eq_true rfl))
  """

  def fingerprint(:pure),
    do: Lynx.Rust.Fingerprint.digest([@scalar_contents, @try_contents, @loop_contents])

  def fingerprint(:runtime),
    do:
      Lynx.Rust.Fingerprint.digest([
        "effectful-calls-v1\n",
        @contents,
        @scalar_contents,
        @try_contents
      ])

  def configuration!(:pure, output, prefix) do
    loop_module = (prefix |> String.split(".") |> hd()) <> ".NativeLoops"

    loops =
      install!(
        output,
        prefix,
        "NativeLoops",
        @loop_marker,
        String.replace(@loop_contents, "__LOOP_NAMESPACE__", loop_module)
      )

    modules = [scalars!(output, prefix), try!(output, prefix), loops]
    {"RustM", ["-extra-includes", Enum.join(modules, ",")], modules}
  end

  def configuration!(:runtime, output, prefix) do
    module = install!(output, prefix, "NativeRuntime", @marker, @contents)
    modules = [module, scalars!(output, prefix), try!(output, prefix)]

    {"Lynx.NativeM",
     [
       "-lean-result-monad",
       "Lynx.NativeM",
       "-loops-no-rec",
       "-extra-includes",
       Enum.join(modules, ",")
     ], modules}
  end

  def configuration!(other, _output, _prefix),
    do: raise(ArgumentError, "unsupported Rust execution model: #{inspect(other)}")

  def install_extracted_notation!(output, prefix, %{"aeneas_version" => version}, calls) do
    features = String.split(version, "+")

    # Lean 4.35 must know the length in a borrowed array's back-function
    # type before it elaborates a tuple pattern. The standard #usize notation
    # defers its bound proof. A closed numeral can prove the same bound by
    # reduction, without changing the extracted tuple or its continuation.
    notation =
      if "tuple-patterns-v1" in features, do: @usize_literal, else: ""

    notation =
      if "local-resource-defaults-v1" in features,
        do: notation <> Lynx.Rust.ResourceModels.default_notation(calls),
        else: notation

    if notation != "" do
      path = Path.join(output, String.replace(prefix, ".", "/") <> "/Funs.lean")
      source = File.read!(path)
      header = "open Aeneas Aeneas.Std RustM ControlFlow Error\n"

      case String.split(source, header, parts: 2) do
        [before, after_header] ->
          File.write!(path, before <> header <> notation <> after_header)

        [_] ->
          raise ArgumentError, "unexpected Aeneas function header in #{path}"
      end
    end
  end

  # Aeneas emits one fixed-point application at the entry of each rust_loop
  # wrapper. Bind that operator without changing Rust identifiers or loop bodies.
  def bind_loop_operator!("Lynx.NativeM", output, prefix, translation) do
    path = Path.join(output, String.replace(prefix, ".", "/") <> "/Funs.lean")
    source = File.read!(path)

    wrappers =
      Enum.count(translation["functions"], &match?(%{"loop" => %{"is_body" => false}}, &1))

    # Cross-crate functions carry a rust_fun path alongside rust_loop. Its
    # quoted Rust path may contain brackets, and the signature can span lines.
    entry =
      ~r/^(@\[rust_loop(?:,(?:[^"\]]|"(?:[^"\\]|\\.)*")*)?\]\ndef [^\n]*(?:\n [^\n]*)*? := do\n  monadLift \()(?:Lynx\.NativeM\.)?loop(?=\s)/m

    unless length(Regex.scan(entry, source)) == wrappers,
      do: raise(ArgumentError, "Aeneas native loop wrappers do not match translation metadata")

    bound = Regex.replace(entry, source, "\\1Lynx.NativeM.loop")
    if bound != source, do: File.write!(path, bound)
  end

  def bind_loop_operator!("RustM", _output, _prefix, _translation), do: :ok

  defp try!(output, prefix),
    do: install!(output, prefix, "NativeTry", @try_marker, @try_contents)

  defp scalars!(output, prefix),
    do: install!(output, prefix, "NativeScalars", @scalar_marker, @scalar_contents)

  defp install!(output, prefix, suffix, marker, contents) do
    module = (prefix |> String.split(".") |> hd()) <> "." <> suffix
    path = Path.join(output, String.replace(module, ".", "/") <> ".lean")

    case File.read(path) do
      {:ok, existing} ->
        unless String.starts_with?(existing, marker),
          do: raise(ArgumentError, "refusing to overwrite a user Lean module: #{path}")

      {:error, :enoent} ->
        :ok

      _ ->
        raise ArgumentError, "refusing to overwrite a user Lean module: #{path}"
    end

    File.mkdir_p!(Path.dirname(path))
    File.write!(path, marker <> contents)
    module
  end
end
