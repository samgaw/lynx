defmodule Lynx.Rust.FormatModels do
  @moduledoc false
  alias Lynx.Rust.{Constants, LLBC}

  # The bounded runtime is not permission to use arbitrary formatting operations.
  # Check default format constructors, writers and every concrete Display
  # dictionary. Debug, options and custom writers stay closed.
  @source Path.expand("../../../priv/lean/LynxRustFormatting.lean", __DIR__)
  @external_resource @source
  @contents File.read!(@source)
  @marker "-- Generated by Lynx: bounded default formatting models.\n"

  def scope(audit, prefix) do
    if enabled?(audit.external_calls) do
      Enum.reduce([:external_calls, :available_external_calls], audit, fn key, audit ->
        Map.update!(audit, key, fn calls ->
          Map.new(calls, fn {id, model} ->
            {id,
             if(model[:bounded_formatting],
               do:
                 Map.merge(model, %{
                   import: module(prefix),
                   lean: String.replace_prefix(model.lean, "Aeneas.Std.", "Lynx.RustFormatting."),
                   builtin: false,
                   backend_rust_name: "lynx_format::function_#{id}"
                 }),
               else: model
             )}
          end)
        end)
      end)
    else
      audit
    end
  end

  def type_models(calls, prefix) do
    if enabled?(calls) do
      for suffix <- ~w(Formatter Arguments rt::Argument) do
        %{
          rust: "core::fmt::" <> suffix,
          backend_rust_name: "lynx_format::" <> String.replace(suffix, "::", "_"),
          lean: "Lynx.RustFormatting.core.fmt." <> String.replace(suffix, "::", "."),
          import: module(prefix),
          label:
            "Bounded default-format representation; Rust core/alloc and allocation remain external models"
        }
      end
    else
      []
    end
  end

  # Case-distinct backend-only trait spelling avoids the reserved pattern
  # while retaining Aeneas's CoreFmtDisplay instance names for client proofs.
  def external_names(calls) do
    if enabled?(calls) do
      %{
        "trait_decls" => [
          %{
            "rust_pattern" => "Core::fmt::Display",
            "extract_name" => "Lynx.RustFormatting.core.fmt.Display",
            "constructor" => "Lynx.RustFormatting.core.fmt.Display.mk"
          }
        ],
        "trait_items" => [
          %{
            "trait" => "Core::fmt::Display",
            "kind" => "method",
            "rust" => "fmt",
            "extract" => "fmt"
          }
        ]
      }
    else
      %{}
    end
  end

  # Only already audited foreign models are renamed. Definition IDs, bodies,
  # signatures and call operands remain unchanged; reports use the raw LLBC.
  # This avoids collisions with Aeneas's packaged, non-overridable fmt models.
  def lower_names!(document, audit) do
    calls = audit.available_external_calls

    if enabled?(audit.external_calls) do
      expected =
        Lynx.Rust.LLBCJson.restore_type_references!(
          %{"translated" => audit.translated},
          %{"translated" => audit.translated}
        )["translated"]

      actual =
        Lynx.Rust.LLBCJson.restore_type_references!(
          document,
          document
        )["translated"]

      same = fn kind, id ->
        keys = ["item_meta", "needs_drop"]

        case {Enum.find(actual[kind], &(&1 && &1["def_id"] == id)),
              Enum.find(expected[kind], &(&1 && &1["def_id"] == id))} do
          {%{} = actual, %{} = expected} -> Map.drop(actual, keys) == Map.drop(expected, keys)
          _ -> false
        end
      end

      functions =
        for {id, model} <- calls,
            model[:bounded_formatting],
            do:
              {"fun_decls", id, model.function["item_meta"]["name"],
               path(~w(lynx_format) ++ ["function_#{id}"])}

      ctx = %{translated: audit.translated, refs: audit.references}

      types =
        for suffix <- ~w(Formatter Arguments rt::Argument),
            type <- document["translated"]["type_decls"],
            type && type["item_meta"]["name"] == path(~w(core fmt) ++ String.split(suffix, "::")) do
          regions = [region(0)]
          args = Map.put(arguments([]), "regions", regions)
          actual = %{"Adt" => %{"id" => type["def_id"], "builtin" => nil, "generics" => args}}

          unless same.("type_decls", type["def_id"]) and
                   named_type?(actual, ~w(core fmt) ++ String.split(suffix, "::"), regions, ctx),
                 do: raise(ArgumentError, "formatting alias requires its audited opaque type")

          {"type_decls", type["def_id"], type["item_meta"]["name"],
           path(["lynx_format", String.replace(suffix, "::", "_")])}
        end

      traits =
        for trait <- document["translated"]["trait_decls"],
            trait && trait["item_meta"]["name"] == path(~w(core fmt Display)) do
          unless same.("trait_decls", trait["def_id"]) and
                   display_trait?(trait["def_id"], ctx),
                 do: raise(ArgumentError, "formatting alias requires its audited Display trait")

          {"trait_decls", trait["def_id"], trait["item_meta"]["name"], path(~w(Core fmt Display))}
        end

      aliases = functions ++ types ++ traits

      renamed =
        Enum.reduce(aliases, document, fn {kind, id, original, alias_name}, document ->
          rows = document["translated"][kind]
          matches = Enum.filter(rows, &(&1 && &1["def_id"] == id))

          unless length(matches) == 1 and hd(matches)["item_meta"]["name"] == original and
                   hd(matches)["item_meta"]["is_local"] == false and
                   (kind != "fun_decls" or
                      (hd(matches)["body"] == "Opaque" and same.("fun_decls", id))),
                 do:
                   raise(
                     ArgumentError,
                     "formatting alias requires its original audited foreign declaration"
                   )

          if Enum.any?(rows, &(&1 && &1["item_meta"]["name"] == alias_name)),
            do: raise(ArgumentError, "formatting alias collides with another declaration")

          update_in(document, ["translated", kind], fn rows ->
            Enum.map(rows, fn row ->
              if row && row["def_id"] == id,
                do: put_in(row, ["item_meta", "name"], alias_name),
                else: row
            end)
          end)
        end)

      {renamed, aliases}
    else
      {document, []}
    end
  end

  def restore_report_names(translation, []), do: translation

  def restore_report_names(translation, aliases) do
    if Enum.any?(aliases, fn {kind, _, original, renamed} ->
         kind == "trait_decls" and original == path(~w(core fmt Display)) and
           renamed == path(~w(Core fmt Display))
       end) do
      Map.update!(translation, "functions", fn functions ->
        Enum.map(functions, fn row ->
          name = String.replace(row["rust_name"], "{Core::fmt::Display<", "{core::fmt::Display<")

          if name == row["rust_name"],
            do: row,
            else:
              row |> Map.put("backend_rust_name", row["rust_name"]) |> Map.put("rust_name", name)
        end)
      end)
    else
      translation
    end
  end

  def install!(calls, output, prefix) do
    if enabled?(calls) do
      module = module(prefix)
      path = Path.join(output, String.replace(module, ".", "/") <> ".lean")

      case File.read(path) do
        {:ok, existing} ->
          unless String.starts_with?(existing, @marker),
            do: raise(ArgumentError, "refusing to overwrite a user Lean module: #{path}")

        {:error, :enoent} ->
          :ok

        {:error, reason} ->
          raise File.Error, reason: reason, action: "read formatting model", path: path
      end

      File.mkdir_p!(Path.dirname(path))
      File.write!(path, @marker <> @contents)
      [module]
    else
      []
    end
  end

  defp enabled?(calls), do: Enum.any?(calls, fn {_id, model} -> model[:bounded_formatting] end)
  defp module(prefix), do: hd(String.split(prefix, ".")) <> ".NativeFormatting"

  def resolve(function, translated, refs) do
    ctx = %{translated: translated, refs: refs, constants: constant_references(translated, %{})}

    with %{
           "body" => "Opaque",
           "signature" => %{"is_unsafe" => unsafe, "is_variadic" => false, "abi" => "Rust"},
           "item_meta" => %{"name" => name}
         } <- function do
      case {unsafe, name} do
        {false,
         [%{"Ident" => ["alloc", 0]}, %{"Ident" => ["fmt", 0]}, %{"Ident" => ["format", 0]}]} ->
          allocated_format_model(function, ctx)

        {false,
         [
           %{"Ident" => ["alloc", 0]},
           %{"Ident" => ["string", 0]},
           %{"Impl" => %{"Trait" => impl}},
           %{"Ident" => ["to_string", 0]}
         ]} ->
          to_string_model(function, impl, ctx)

        {false,
         [
           %{"Ident" => ["core", 0]},
           %{"Ident" => ["fmt", 0]},
           %{"Impl" => %{"Ty" => %{"skip_binder" => parent, "params" => params}}},
           %{"Ident" => ["write_str", 0]}
         ]} ->
          write_str_model(function, parent, params, ctx)

        {false,
         [
           %{"Ident" => ["core", 0]},
           %{"Ident" => ["fmt", 0]},
           %{"Ident" => ["rt", 0]},
           %{"Impl" => %{"Ty" => %{"skip_binder" => parent, "params" => params}}},
           %{"Ident" => ["new_display", 0]}
         ]} ->
          new_display_model(function, parent, params, ctx)

        {unsafe,
         [
           %{"Ident" => ["core", 0]},
           %{"Ident" => ["fmt", 0]},
           %{"Impl" => %{"Ty" => %{"skip_binder" => parent, "params" => params}}},
           %{"Ident" => [method, 0]}
         ]} ->
          formatter_model(function, unsafe, method, parent, params, ctx)

        {false, name} ->
          standard_display_model(function, name, ctx)

        _ ->
          nil
      end
    else
      _ -> nil
    end
  end

  defp allocated_format_model(function, ctx) do
    sig = expand(function["signature"], ctx)

    with "Normal" <- function["src"],
         true <- plain_parameters?(function["generics"], 1, 0),
         [args] <- sig["inputs"],
         true <- named_type?(args, ~w(core fmt Arguments), [region(0)], ctx),
         true <- named_type?(sig["output"], ~w(alloc string String), [], ctx) do
      model(
        "alloc::fmt::format",
        "Aeneas.Std.alloc.fmt.format",
        false,
        "Bounded allocated default-format model invoking checked arguments and actual renderers; formatter errors panic; oversized output exhausts verification; Rust alloc implementation and native allocation unverified"
      )
    else
      _ -> nil
    end
  end

  defp to_string_model(function, impl_id, ctx) do
    ctx = Map.put(ctx, :traits, trait_references(ctx.translated, %{}))
    sig = expand(function["signature"], ctx)
    generics = expand(function["generics"], ctx)

    with true <- parameters?(generics, 1, 1),
         %{"trait_clauses" => [clause]} <- generics,
         {:ok, display} <- display_clause(clause, ctx),
         true <- generics["outlives"] == [outlives(%{"Lub" => variable(0)}, region(0))],
         true <- sig["inputs"] == [reference(region(0), variable(0), "Shared")],
         true <- named_type?(sig["output"], ~w(alloc string String), [], ctx),
         %{
           "is_negative" => false,
           "is_unsafe" => false,
           "src" => "Normal",
           "generics" => impl_params,
           "impl_trait" => %{"id" => to_string, "generics" => impl_trait_args}
         } = impl <- declaration(ctx, "trait_impls", impl_id),
         true <- parameters?(impl_params, 0, 1),
         [impl_clause] <- impl_params["trait_clauses"],
         {:ok, ^display} <- display_clause(impl_clause, ctx),
         true <- impl_params["outlives"] == [],
         true <- expand(impl_trait_args, ctx) == arguments([variable(0)]),
         true <- to_string_trait?(to_string, ctx),
         true <- method_identity?(function, impl, to_string, ctx) do
      model(
        "alloc::string::{alloc::string::ToString<@T>}::to_string",
        "Aeneas.Std.alloc.string.ToString.to_string",
        false,
        "Bounded default ToString model invoking the actual audited Display method; allocation success assumed; Rust alloc implementation not verified"
      )
      |> Map.put(:display_trait, display)
    else
      _ -> nil
    end
  end

  defp write_str_model(function, parent, params, ctx) do
    sig = expand(function["signature"], ctx)
    generics = expand(function["generics"], ctx)
    parent = parent |> expand(ctx) |> free_bound()

    with true <- plain_parameters?(params, 1, 0),
         true <- named_type?(parent, ~w(core fmt Formatter), [region(0)], ctx),
         true <- plain_parameters?(generics, 3, 0, [outlives(region(0), region(1))]),
         [writer, text] <- sig["inputs"],
         true <- writer == reference(region(1), parent, "Mut"),
         %{"Ref" => [text_region, string, "Shared"]} <- text,
         true <- text_region == region(2),
         true <- str_type?(string),
         true <- fmt_result?(sig["output"], ctx) do
      model(
        "core::fmt::{core::fmt::Formatter<'a>}::write_str",
        "Aeneas.Std.core.fmt.Formatter.write_str",
        true,
        "Bounded default UTF-8 string writer model; allocation success assumed; unsupported size is a verification cutoff; Rust core implementation not verified"
      )
    else
      _ -> nil
    end
  end

  defp new_display_model(function, parent, params, ctx) do
    sig = expand(function["signature"], ctx)
    generics = expand(function["generics"], ctx)

    with true <- plain_parameters?(params, 1, 0),
         true <-
           named_type?(
             parent |> expand(ctx) |> free_bound(),
             ~w(core fmt rt Argument),
             [region(0)],
             ctx
           ),
         true <- parameters?(generics, 2, 1),
         [clause] <- generics["trait_clauses"],
         {:ok, display} <- display_clause(clause, ctx),
         true <- generics["outlives"] == [outlives(%{"Lub" => variable(0)}, region(1))],
         true <- sig["inputs"] == [reference(region(1), variable(0), "Shared")],
         true <- named_type?(sig["output"], ~w(core fmt rt Argument), [region(1)], ctx) do
      model(
        "core::fmt::rt::{core::fmt::rt::Argument<'0>}::new_display",
        "Aeneas.Std.core.fmt.rt.Argument.new_display",
        true,
        "Bounded default Display argument retaining the actual audited renderer; Rust core implementation not verified"
      )
      |> Map.merge(%{display_trait: display, display_regions: 2})
    else
      _ -> nil
    end
  end

  defp formatter_model(function, unsafe, method, parent, params, ctx) do
    sig = expand(function["signature"], ctx)
    generics = expand(function["generics"], ctx)
    parent = parent |> expand(ctx) |> free_bound()

    cond do
      method == "write_fmt" and unsafe == false and plain_parameters?(params, 1, 0) and
        named_type?(parent, ~w(core fmt Formatter), [region(0)], ctx) and
          plain_parameters?(generics, 3, 0, [outlives(region(0), region(1))]) ->
        case sig["inputs"] do
          [writer, args] ->
            if writer == reference(region(1), parent, "Mut") and
                 named_type?(args, ~w(core fmt Arguments), [region(2)], ctx) and
                 fmt_result?(sig["output"], ctx),
               do:
                 model(
                   "core::fmt::{core::fmt::Formatter<'a>}::write_fmt",
                   "Aeneas.Std.core.fmt.Formatter.write_fmt",
                   true,
                   "Bounded default-format execution of checked template and actual renderers; allocation success assumed; Rust core implementation not verified"
                 )

          _ ->
            nil
        end

      method == "new" and unsafe == true and plain_parameters?(params, 1, 0) and
          named_type?(parent, ~w(core fmt Arguments), [region(0)], ctx) ->
        arguments_constructor_model(sig, generics, ctx)

      true ->
        nil
    end
  end

  defp arguments_constructor_model(sig, generics, ctx) do
    usize = %{"Scalar" => %{"Integer" => %{"Unsigned" => "Usize"}}}
    u8 = %{"Scalar" => %{"Integer" => %{"Unsigned" => "U8"}}}

    with %{
           "regions" => [r],
           "types" => [],
           "const_generics" => [n, m],
           "trait_clauses" => [],
           "outlives" => [],
           "trait_type_constraints" => []
         } <- generics,
         true <- r["index"] == 0 and n["index"] == 0 and m["index"] == 1,
         true <- n["ty"] == usize and m["ty"] == usize,
         [template, args] <- sig["inputs"],
         true <-
           template ==
             reference(
               region(0),
               %{"Array" => [u8, [%{"Var" => %{"Free" => 0}}, usize], nil]},
               "Shared"
             ),
         %{"Ref" => [arg_region, %{"Array" => [argument, size, nil]}, "Shared"]} <- args,
         true <- arg_region == region(0) and size == [%{"Var" => %{"Free" => 1}}, usize],
         true <- named_type?(argument, ~w(core fmt rt Argument), [region(0)], ctx),
         true <- named_type?(sig["output"], ~w(core fmt Arguments), [region(0)], ctx) do
      model(
        "core::fmt::{core::fmt::Arguments<'a>}::new",
        "Aeneas.Std.core.fmt.Arguments.new",
        true,
        "Bounded format-argument constructor: supported UTF-8 template and argument indices checked before success; unsupported/invalid inputs cut off; Rust core implementation not verified"
      )
    else
      _ -> nil
    end
  end

  defp standard_display_model(function, name, ctx) do
    source =
      case name do
        [
          %{"Ident" => ["core", 0]},
          %{"Ident" => ["fmt", 0]},
          %{"Ident" => ["num", 0]},
          %{"Ident" => ["imp", 0]},
          %{"Impl" => %{"Trait" => id}},
          %{"Ident" => ["fmt", 0]}
        ] ->
          {:scalar, id}

        [
          %{"Ident" => ["alloc", 0]},
          %{"Ident" => ["string", 0]},
          %{"Impl" => %{"Trait" => id}},
          %{"Ident" => ["fmt", 0]}
        ] ->
          {:string, id}

        [
          %{"Ident" => ["core", 0]},
          %{"Ident" => ["fmt", 0]},
          %{"Impl" => %{"Trait" => id}},
          %{"Ident" => ["fmt", 0]}
        ] ->
          {:core, id}

        _ ->
          nil
      end

    if source do
      {kind, id} = source
      ctx = Map.put(ctx, :traits, trait_references(ctx.translated, %{}))

      with %{
             "src" => "Normal",
             "is_negative" => false,
             "is_unsafe" => false,
             "consts" => [],
             "types" => [],
             "implied_trait_refs" => [],
             "impl_trait" => %{"id" => trait, "generics" => args}
           } = impl <- declaration(ctx, "trait_impls", id),
           true <- display_trait?(trait, ctx),
           %{"regions" => [], "const_generics" => [], "trait_refs" => [], "types" => [self]} <-
             expand(args, ctx),
           true <- method_identity?(function, impl, trait, ctx) do
        standard_display_kind(function, impl, kind, self, trait, ctx)
      else
        _ -> nil
      end
    end
  end

  defp standard_display_kind(function, impl, kind, self, trait, ctx) do
    if plain_parameters?(impl["generics"], 0, 0) and display_signature?(function, self, ctx) do
      spec =
        case {kind, self} do
          {:scalar, %{"Scalar" => %{"Integer" => %{"Signed" => width}}}}
          when width in ~w(I8 I16 I32 I64 I128 Isize) ->
            {"core::fmt::num::imp::{core::fmt::Display<#{String.downcase(width)}>}::fmt",
             "Aeneas.Std.core.fmt.num.imp.Display#{width}.fmt", true}

          {:scalar, %{"Scalar" => %{"Integer" => %{"Unsigned" => width}}}}
          when width in ~w(U8 U16 U32 U64 U128 Usize) ->
            {"core::fmt::num::imp::{core::fmt::Display<#{String.downcase(width)}>}::fmt",
             "Aeneas.Std.core.fmt.num.imp.Display#{width}.fmt", true}

          {:string, _} ->
            if named_type?(self, ~w(alloc string String), [], ctx),
              do:
                {"alloc::string::{core::fmt::Display<alloc::string::String>}::fmt",
                 "Aeneas.Std.alloc.string.DisplayString.fmt", false}

          {:core, _} ->
            if str_type?(self),
              do:
                {"core::fmt::{core::fmt::Display<str>}::fmt",
                 "Aeneas.Std.core.fmt.DisplayStr.fmt", false}

          _ ->
            nil
        end

      if spec do
        {rust, lean, builtin} = spec

        model(
          rust,
          lean,
          builtin,
          "Bounded default integer/string Display writer model; allocation success assumed; Rust implementation not verified"
        )
        |> Map.put(:display_renderer, true)
      end
    else
      if kind == :core, do: shared_display_model(function, impl, self, trait, ctx)
    end
  end

  defp shared_display_model(function, impl, self, trait, ctx) do
    fp = expand(function["generics"], ctx)
    ip = expand(impl["generics"], ctx)
    sig = expand(function["signature"], ctx)

    with true <- parameters?(ip, 1, 1),
         true <- parameters?(fp, 4, 1),
         [ic] <- ip["trait_clauses"],
         [fc] <- fp["trait_clauses"],
         {:ok, ^trait} <- display_clause(ic, ctx),
         {:ok, ^trait} <- display_clause(fc, ctx),
         true <- ip["outlives"] == [outlives(%{"Lub" => variable(0)}, region(0))],
         true <-
           fp["outlives"] == [
             outlives(region(0), region(1)),
             outlives(%{"Lub" => variable(0)}, region(0)),
             outlives(region(3), region(2))
           ],
         true <- self == reference(region(0), variable(0), "Shared"),
         [input, writer] <- sig["inputs"],
         true <- input == reference(region(1), self, "Shared"),
         %{"Ref" => [r, formatter, "Mut"]} <- writer,
         true <- r == region(2),
         true <- named_type?(formatter, ~w(core fmt Formatter), [region(3)], ctx),
         true <- fmt_result?(sig["output"], ctx) do
      model(
        "core::fmt::{core::fmt::Display<&'0 @T>}::fmt",
        "Aeneas.Std.core.fmt.DisplayShared.fmt",
        false,
        "Default shared-reference Display delegates to the actual audited inner dictionary; Rust core implementation not verified"
      )
      |> Map.merge(%{
        display_renderer: true,
        display_delegate: trait,
        display_trait: trait,
        display_regions: 4
      })
    else
      _ -> nil
    end
  end

  def audit(functions, models, translated, refs) do
    ctx = %{
      translated: translated,
      refs: refs,
      constants: constant_references(translated, %{}),
      models: models,
      traits: trait_references(translated, %{}),
      functions: Map.new(Enum.reject(translated["fun_decls"], &is_nil/1), &{&1["def_id"], &1}),
      implementations: MapSet.new(functions, & &1["def_id"])
    }

    Enum.reduce_while(functions, {:ok, %{}}, fn function, {:ok, dependencies} ->
      try do
        ids = dispatches(function["body"], ctx) |> Enum.uniq() |> Enum.sort()
        {:cont, {:ok, Map.put(dependencies, function["def_id"], ids)}}
      rescue
        error in ArgumentError -> {:halt, {:error, function, Exception.message(error)}}
      end
    end)
  end

  defp dispatches(
         %{
           "Call" => %{
             "call" => %{
               "func" => %{"Regular" => %{"kind" => %{"Fun" => id}, "generics" => args}}
             }
           }
         } = node,
         ctx
       ) do
    direct =
      case ctx.models[id] do
        %{display_trait: trait} = model ->
          display_methods!(args, trait, Map.get(model, :display_regions, 1), ctx)

        _ ->
          []
      end

    direct ++ Enum.flat_map(Map.values(node), &dispatches(&1, ctx))
  end

  defp dispatches(node, ctx) when is_map(node),
    do: Enum.flat_map(Map.values(node), &dispatches(&1, ctx))

  defp dispatches(nodes, ctx) when is_list(nodes), do: Enum.flat_map(nodes, &dispatches(&1, ctx))
  defp dispatches(_, _), do: []

  # A dictionary is not a verified contract. Follow its actual implementation
  # method, and permit standard renderers only through the closed typed catalogue.
  defp display_methods!(args, trait, regions, ctx) do
    with %{"regions" => rs, "types" => [self], "const_generics" => [], "trait_refs" => [ref]} <-
           args,
         true <- is_list(rs) and length(rs) == regions do
      display_reference!(ref, trait, expand(self, ctx), ctx, [])
    else
      _ -> display_failure!()
    end
  end

  defp display_reference!(ref, trait, self, ctx, seen) do
    with %{
           "kind" => %{"TraitImpl" => %{"id" => impl_id, "generics" => actual_args}},
           "trait_decl_ref" => %{"id" => ^trait, "generics" => trait_args}
         } <- trait_reference(ref, ctx.traits),
         true <- expand(trait_args, ctx) == arguments([self]),
         true <- {impl_id, self} not in seen,
         %{
           "src" => "Normal",
           "is_negative" => false,
           "is_unsafe" => false,
           "consts" => [],
           "types" => [],
           "implied_trait_refs" => [],
           "impl_trait" => impl_trait,
           "generics" => params,
           "methods" => [%{"skip_binder" => %{"id" => method}}]
         } = impl <- declaration(ctx, "trait_impls", impl_id),
         true <- instance_arguments?(actual_args, params),
         true <-
           instantiate(expand(impl_trait, ctx), actual_args, ctx) == %{
             "id" => trait,
             "generics" => arguments([self])
           },
         %{} = function <- ctx.functions[method],
         true <- method_identity?(function, impl, trait, ctx) do
      case ctx.models[method] do
        %{display_delegate: ^trait} ->
          with %{
                 "regions" => [_],
                 "types" => [inner],
                 "const_generics" => [],
                 "trait_refs" => [nested]
               } <- actual_args do
            [
              method
              | display_reference!(nested, trait, expand(inner, ctx), ctx, [
                  {impl_id, self} | seen
                ])
            ]
          else
            _ -> display_failure!()
          end

        %{display_renderer: true} ->
          [method]

        _ ->
          if MapSet.member?(ctx.implementations, method) and plain_parameters?(params, 0, 0) and
               Constants.empty_arguments?(actual_args) and display_signature?(function, self, ctx) do
            [method]
          else
            display_failure!()
          end
      end
    else
      _ -> display_failure!()
    end
  end

  defp instance_arguments?(
         %{"regions" => rs, "types" => ts, "const_generics" => [], "trait_refs" => refs},
         params
       )
       when is_list(rs) and is_list(ts) and is_list(refs) do
    length(rs) == length(params["regions"]) and length(ts) == length(params["types"]) and
      length(refs) == length(params["trait_clauses"])
  end

  defp instance_arguments?(_, _), do: false

  defp instantiate(%{"TypeVar" => %{"Free" => index}}, args, ctx),
    do: expand(Enum.at(args["types"], index), ctx)

  defp instantiate(%{"Var" => %{"Free" => index}}, args, _), do: Enum.at(args["regions"], index)

  defp instantiate(map, args, ctx) when is_map(map),
    do: Map.new(map, fn {k, v} -> {k, instantiate(v, args, ctx)} end)

  defp instantiate(list, args, ctx) when is_list(list),
    do: Enum.map(list, &instantiate(&1, args, ctx))

  defp instantiate(value, _, _), do: value

  defp display_failure!,
    do:
      raise(
        ArgumentError,
        "Display requires a monomorphic extracted implementation or approved typed renderer with matching dictionary, method identity and signature; external renderers are not implicitly approved"
      )

  # Shared by the closed Encoder catalogue: this is a generic compiler method
  # identity/binder check, independent of formatting semantics.
  @doc false
  def method_identity?(function, impl, trait, ctx) do
    id = function["def_id"]
    impl_id = impl["def_id"]

    with %{
           "TraitImpl" => %{
             "impl_ref" => %{"id" => ^impl_id},
             "trait_ref" => %{"id" => ^trait},
             "item_id" => 0,
             "reuses_default" => false
           }
         } <- function["src"],
         [
           %{
             "kind" => %{"TraitMethod" => [^trait, 0]},
             "params" => params,
             "skip_binder" => %{"id" => ^id, "generics" => args}
           }
         ] <- impl["methods"],
         true <-
           plain_parameters?(
             params,
             length(function["generics"]["regions"]) - length(impl["generics"]["regions"]),
             0
           ),
         true <- generic_arguments?(args, impl, ctx, :method, function) do
      # The method's source must refer to the same impl and trait, including Self.
      source = function["src"]["TraitImpl"]

      expand(source["trait_ref"], ctx) == expand(impl["impl_trait"], ctx) and
        generic_arguments?(source["impl_ref"]["generics"], impl, ctx, :impl, function)
    else
      _ -> false
    end
  end

  defp generic_arguments?(args, impl, ctx, kind, function) do
    n = length(function["generics"]["regions"]) - length(impl["generics"]["regions"])

    inherited = Enum.map(impl["generics"]["regions"], &region(&1["index"]))

    regions =
      inherited ++
        if(kind == :method,
          do: Enum.map(indices(n), &%{"Var" => %{"Bound" => [0, &1]}}),
          else: []
        )

    expected =
      arguments(Enum.map(impl["generics"]["types"], &variable(&1["index"])))
      |> Map.put("regions", regions)

    clauses = impl["generics"]["trait_clauses"]
    refs = args["trait_refs"]

    expand(Map.put(args, "trait_refs", []), ctx) == expected and is_list(refs) and
      length(refs) == length(clauses) and
      Enum.all?(Enum.zip(refs, clauses), fn {ref, clause} ->
        case trait_reference(ref, ctx.traits) do
          %{
            "kind" => %{"Clause" => [%{"Free" => index}, %{"regions" => []}]},
            "trait_decl_ref" => decl
          } ->
            index == clause["clause_id"] and
              expand(decl, ctx) == expand(clause["trait_"]["skip_binder"], ctx)

          _ ->
            false
        end
      end)
  end

  defp display_signature?(function, self, ctx) do
    sig = expand(function["signature"], ctx)
    params = expand(function["generics"], ctx)
    expected = [outlives(region(2), region(1))]

    with true <- plain_parameters?(params, 3, 0, params["outlives"]),
         true <- params["outlives"] in [[], expected],
         %{
           "is_unsafe" => false,
           "is_variadic" => false,
           "abi" => "Rust",
           "inputs" => [input, writer]
         } <- sig,
         true <- input == reference(region(0), self, "Shared"),
         %{"Ref" => [writer_region, formatter, "Mut"]} <- writer,
         true <- writer_region == region(1),
         true <- named_type?(formatter, ~w(core fmt Formatter), [region(2)], ctx) do
      fmt_result?(sig["output"], ctx)
    else
      _ -> false
    end
  end

  defp display_clause(
         %{
           "clause_id" => 0,
           "trait_" => %{
             "regions" => [],
             "outlives" => [],
             "skip_binder" => %{"id" => id, "generics" => args}
           }
         },
         ctx
       ) do
    if expand(args, ctx) == arguments([variable(0)]) and display_trait?(id, ctx),
      do: {:ok, id},
      else: :error
  end

  defp display_clause(_, _), do: :error

  defp display_trait?(id, ctx) do
    case declaration(ctx, "trait_decls", id) do
      %{
        "item_meta" => %{"name" => name},
        "is_unsafe" => false,
        "generics" => params,
        "consts" => [],
        "types" => [],
        "implied_clauses" => [],
        "methods" => [
          %{
            "kind" => %{"TraitMethod" => [^id, 0]},
            "params" => method_params,
            "skip_binder" => %{"name" => "fmt", "signature" => sig, "default" => nil}
          }
        ]
      } ->
        name == path(~w(core fmt Display)) and plain_parameters?(params, 0, 1) and
          plain_parameters?(method_params, 3, 0) and
          display_signature?(
            %{"signature" => sig |> expand(ctx) |> free_bound(), "generics" => method_params(3)},
            variable(0),
            ctx
          )

      _ ->
        false
    end
  end

  defp to_string_trait?(id, ctx) do
    case declaration(ctx, "trait_decls", id) do
      %{
        "item_meta" => %{"name" => name},
        "is_unsafe" => false,
        "generics" => params,
        "consts" => [],
        "types" => [],
        "implied_clauses" => [],
        "methods" => [
          %{
            "kind" => %{"TraitMethod" => [^id, 0]},
            "params" => method_params,
            "skip_binder" => %{"name" => "to_string", "signature" => sig, "default" => nil}
          }
        ]
      } ->
        sig = sig |> expand(ctx) |> free_bound()

        name == path(~w(alloc string ToString)) and plain_parameters?(params, 0, 1) and
          plain_parameters?(method_params, 1, 0) and
          sig["is_unsafe"] == false and sig["abi"] == "Rust" and sig["is_variadic"] == false and
          sig["inputs"] == [reference(region(0), variable(0), "Shared")] and
          named_type?(sig["output"], ~w(alloc string String), [], ctx)

      _ ->
        false
    end
  end

  defp fmt_result?(%{"Adt" => %{"id" => id, "builtin" => nil, "generics" => args}}, ctx) do
    case args do
      %{"regions" => [], "const_generics" => [], "trait_refs" => [], "types" => [unit, error]} ->
        LLBC.result_type?(id, %{translated: ctx.translated, references: ctx.refs}) and
          match?(
            %{
              "Adt" => %{
                "builtin" => "Tuple",
                "generics" => %{
                  "regions" => [],
                  "types" => [],
                  "const_generics" => [],
                  "trait_refs" => []
                }
              }
            },
            unit
          ) and
          named_type?(error, ~w(core fmt Error), [], ctx)

      _ ->
        false
    end
  end

  defp fmt_result?(_, _), do: false

  defp named_type?(
         %{"Adt" => %{"id" => id, "builtin" => nil, "generics" => args}},
         name,
         regions,
         ctx
       ) do
    case declaration(ctx, "type_decls", id) do
      %{"item_meta" => %{"name" => actual}, "kind" => kind, "generics" => params} ->
        bounds = if name == ~w(core fmt Formatter), do: [outlives(region(0), region(0))], else: []
        expected_kind = if name == ~w(core fmt Error), do: %{"Struct" => []}, else: "Opaque"

        actual == path(name) and args == Map.put(arguments([]), "regions", regions) and
          kind == expected_kind and
          plain_parameters?(params, length(regions), 0, bounds)

      _ ->
        false
    end
  end

  defp named_type?(_, _, _, _), do: false

  defp str_type?(%{"Adt" => %{"builtin" => "Str", "generics" => args}}),
    do: Constants.empty_arguments?(args)

  defp str_type?(_), do: false

  defp parameters?(
         %{
           "regions" => regions,
           "types" => types,
           "const_generics" => [],
           "trait_type_constraints" => []
         },
         nr,
         nt
       )
       when is_list(regions) and is_list(types),
       do:
         Enum.map(regions, & &1["index"]) == indices(nr) and
           Enum.map(types, & &1["index"]) == indices(nt)

  defp parameters?(_, _, _), do: false

  defp plain_parameters?(params, nr, nt, outlives \\ []),
    do:
      parameters?(params, nr, nt) and params["trait_clauses"] == [] and
        params["outlives"] == outlives

  defp method_params(n),
    do: %{
      "regions" => Enum.map(indices(n), &%{"index" => &1}),
      "types" => [],
      "const_generics" => [],
      "trait_clauses" => [],
      "outlives" => [],
      "trait_type_constraints" => []
    }

  defp indices(0), do: []
  defp indices(n) when n > 0, do: Enum.to_list(0..(n - 1))
  defp variable(i), do: %{"TypeVar" => %{"Free" => i}}
  defp region(i), do: %{"Var" => %{"Free" => i}}
  defp reference(r, t, kind), do: %{"Ref" => [r, t, kind]}

  defp arguments(types),
    do: %{"regions" => [], "types" => types, "const_generics" => [], "trait_refs" => []}

  defp outlives(left, right),
    do: %{"regions" => [], "outlives" => [], "skip_binder" => [left, right]}

  defp path(parts), do: Enum.map(parts, &%{"Ident" => [&1, 0]})

  defp model(rust, lean, builtin, label),
    do: %{
      rust_name: rust,
      lean: lean,
      builtin: builtin,
      can_fail: true,
      lift: false,
      bounded_formatting: true,
      label: label
    }

  defp expand(%{"Array" => [element, size, rest]}, ctx),
    do: %{"Array" => [expand(element, ctx), expand_constant(size, ctx), rest]}

  defp expand(%{"Value" => [_, value]}, ctx), do: expand(value, ctx)

  defp expand(%{"Deduplicated" => id}, ctx) do
    case ctx.refs[id] do
      nil -> %{"UnknownTypeReference" => id}
      value -> expand(value, ctx)
    end
  end

  defp expand(map, ctx) when is_map(map), do: Map.new(map, fn {k, v} -> {k, expand(v, ctx)} end)
  defp expand(list, ctx) when is_list(list), do: Enum.map(list, &expand(&1, ctx))
  defp expand(value, _), do: value

  defp expand_constant(%{"Value" => [_, [kind, type]]}, ctx), do: [kind, expand(type, ctx)]

  defp expand_constant(%{"Deduplicated" => id}, ctx) do
    case ctx.constants[id] do
      [kind, type] -> [kind, expand(type, ctx)]
      _ -> %{"UnknownConstantReference" => id}
    end
  end

  defp expand_constant(_, _), do: nil

  defp constant_references(%{"Value" => [id, [kind, _] = value]}, refs)
       when is_map(kind) and
              (is_map_key(kind, "Var") or is_map_key(kind, "Integer") or
                 is_map_key(kind, "Discriminant")) do
    if Map.has_key?(refs, id) and refs[id] != value,
      do: raise(ArgumentError, "inconsistent LLBC shared constant identity")

    Map.put(refs, id, value)
  end

  defp constant_references(map, refs) when is_map(map),
    do: Enum.reduce(Map.values(map), refs, &constant_references/2)

  defp constant_references(list, refs) when is_list(list),
    do: Enum.reduce(list, refs, &constant_references/2)

  defp constant_references(_, refs), do: refs

  defp declaration(ctx, key, id),
    do: Enum.find(ctx.translated[key] || [], &(&1 && &1["def_id"] == id))

  # These method binders introduce regions, not additional type parameters.
  defp free_bound(%{"Var" => %{"Bound" => [0, i]}}), do: region(i)
  defp free_bound(map) when is_map(map), do: Map.new(map, fn {k, v} -> {k, free_bound(v)} end)
  defp free_bound(list) when is_list(list), do: Enum.map(list, &free_bound/1)
  defp free_bound(value), do: value

  defp trait_reference(
         %{"regions" => [], "outlives" => [], "skip_binder" => %{"Value" => [_, value]}},
         _
       ),
       do: value

  defp trait_reference(
         %{"regions" => [], "outlives" => [], "skip_binder" => %{"Deduplicated" => id}},
         refs
       ),
       do: refs[id]

  defp trait_reference(_, _), do: nil

  defp trait_references(%{"Value" => [id, %{"kind" => _, "trait_decl_ref" => _} = ref]}, refs) do
    if Map.has_key?(refs, id) and refs[id] != ref,
      do: raise(ArgumentError, "inconsistent LLBC shared trait identity")

    trait_references(ref, Map.put(refs, id, ref))
  end

  defp trait_references(map, refs) when is_map(map),
    do: Enum.reduce(Map.values(map), refs, &trait_references/2)

  defp trait_references(list, refs) when is_list(list),
    do: Enum.reduce(list, refs, &trait_references/2)

  defp trait_references(_, refs), do: refs
end
