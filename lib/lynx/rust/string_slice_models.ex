defmodule Lynx.Rust.StringSliceModels do
  @moduledoc false
  alias Lynx.Rust.{CallModels, ResourceModels, StringModels}
  @source Path.expand("../../../priv/lean/LynxRustStringSlices.lean", __DIR__)
  @external_resource @source
  @contents File.read!(@source)
  @marker "-- Generated by Lynx: checked shared string slices.\n"

  def fingerprint, do: Lynx.Rust.Fingerprint.digest(@contents)

  def resolve(function, translated, refs) do
    safe(function, translated, refs) || unchecked_wrapper(function, translated, refs) ||
      elaboration(function, translated, refs)
  end

  defp safe(function, translated, refs) do
    with %{"body" => "Opaque", "signature" => sig} <- function,
         true <-
           Map.take(sig, ~w(abi is_unsafe is_variadic)) ==
             %{"abi" => "Rust", "is_unsafe" => false, "is_variadic" => false} do
      wrapper(function, translated, refs) || leaf(function, translated, refs)
    else
      _ -> nil
    end
  end

  # Aeneas emits unused methods of a discovered dictionary as well. Give those
  # declarations concrete exhaustion functions, never assumed implementations.
  # They are excluded from the approved-call set; only the checked get slot is
  # executable in the supported subset.
  defp elaboration(f, t, refs) do
    with "Opaque" <- f["body"],
         %{
           "TraitImpl" => %{
             "impl_ref" => %{"id" => impl_id},
             "item_id" => slot,
             "reuses_default" => false
           }
         } <- f["src"],
         true <- slot in 1..5,
         impl when is_map(impl) <- find(t["trait_impls"], impl_id),
         trait = impl["impl_trait"]["id"],
         [%{"skip_binder" => %{"id" => get_id}}] <-
           Enum.filter(impl["methods"], &(&1["kind"] == %{"TraitMethod" => [trait, 0]})),
         get when is_map(get) <- find(t["fun_decls"], get_id),
         %{str_range: kind} <- safe(get, t, refs),
         method = Enum.at(~w(get get_mut get_unchecked get_unchecked_mut index index_mut), slot),
         true <-
           f["item_meta"]["name"] ==
             path(~w(core str traits)) ++
               [%{"Impl" => %{"Trait" => impl_id}}, %{"Ident" => [method, 0]}],
         [%{"skip_binder" => %{"id" => id}}] <-
           Enum.filter(impl["methods"], &(&1["kind"] == %{"TraitMethod" => [trait, slot]})),
         true <- id == f["def_id"] do
      model(
        "core::str::traits::{core::slice::index::SliceIndex<core::ops::range::#{kind}<usize>, str, str>}::#{method}",
        kind <> "Index." <> method
      )
      |> Map.put(:elaboration_only, true)
      |> Map.put(
        :label,
        "Unused string dictionary slot: verification exhaustion, not native semantics"
      )
    else
      _ -> nil
    end
  end

  defp unchecked_wrapper(%{"body" => "Opaque", "signature" => sig} = f, t, refs) do
    if Map.take(sig, ~w(abi is_unsafe is_variadic)) == %{
         "abi" => "Rust",
         "is_unsafe" => true,
         "is_variadic" => false
       },
       do: wrapper(f, t, refs, "get_unchecked")
  end

  defp unchecked_wrapper(_, _, _), do: nil

  defp wrapper(f, t, refs, method \\ "get") do
    with "Normal" <- f["src"],
         [
           %{"Ident" => ["core", 0]},
           %{"Ident" => ["str", 0]},
           %{"Impl" => %{"Ty" => parent}},
           %{"Ident" => [^method, 0]}
         ] <- f["item_meta"]["name"],
         true <- parent["kind"] == "InherentImplBlock" and parent["params"] == params(),
         str = CallModels.expand(parent["skip_binder"], refs),
         true <- str?(str, t, refs),
         p = f["generics"],
         true <- indices(p["regions"]) == [0] and indices(p["types"]) == [0, 1],
         true <- p["const_generics"] == [] and p["trait_type_constraints"] == [],
         true <-
           CallModels.expand(p["outlives"], refs) ==
             Enum.map(
               [1, 0],
               &%{
                 "regions" => [],
                 "outlives" => [],
                 "skip_binder" => [%{"Lub" => variable(&1)}, region()]
               }
             ),
         [
           %{
             "clause_id" => 0,
             "trait_" => %{
               "regions" => [],
               "outlives" => [],
               "skip_binder" => %{"id" => trait, "generics" => actual}
             }
           }
         ] <- p["trait_clauses"],
         true <- trait?(trait, t),
         true <- CallModels.expand(actual, refs) == args([variable(0), str, variable(1)]),
         true <- CallModels.expand(f["signature"]["inputs"], refs) == [ref(str), variable(0)],
         true <-
           if(method == "get",
             do: option?(f["signature"]["output"], ref(variable(1)), t, refs),
             else: CallModels.expand(f["signature"]["output"], refs) == ref(variable(1))
           ) do
      if method == "get" do
        model("core::str::{str}::get", "get") |> Map.put(:str_index_method, 0)
      else
        model("core::str::{str}::get_unchecked", "uncheckedFrom")
        |> Map.merge(%{
          string_unchecked_from: true,
          keep_params: [false, false],
          keep_trait_clauses: [false],
          label:
            "Shared str unchecked RangeFrom borrow model restricted to the extracted standard strip_prefix implementation; invalid UTF-8 boundaries exhaust verification; actual range dictionary is validated; Rust core raw pointers, native layout and borrow lifetime remain unverified"
        })
      end
    else
      _ -> nil
    end
  end

  defp leaf(f, t, refs) do
    with %{
           "TraitImpl" => %{
             "impl_ref" => %{"id" => impl_id, "generics" => impl_args},
             "trait_ref" => %{"id" => trait, "generics" => trait_args},
             "item_id" => 0,
             "reuses_default" => false
           }
         } <- f["src"],
         true <- CallModels.expand(impl_args, refs) == args([]),
         true <-
           f["item_meta"]["name"] ==
             path(~w(core str traits)) ++
               [%{"Impl" => %{"Trait" => impl_id}}, %{"Ident" => ["get", 0]}],
         impl when is_map(impl) <- find(t["trait_impls"], impl_id),
         true <-
           impl["src"] == "Normal" and impl["is_unsafe"] == true and impl["is_negative"] == false,
         true <- impl["generics"] == params(),
         true <- trait?(trait, t),
         true <- impl["impl_trait"]["id"] == trait,
         [range, str, output] <- CallModels.expand(trait_args, refs)["types"],
         true <- str == output and str?(str, t, refs),
         true <- CallModels.expand(trait_args, refs) == args([range, str, str]),
         true <-
           CallModels.expand(impl["impl_trait"]["generics"], refs) == args([range, str, str]),
         kind when kind in ~w(Range RangeFrom RangeTo) <- range_kind(range, t, refs),
         [%{"skip_binder" => %{"id" => id}}] <-
           Enum.filter(impl["methods"], &(&1["kind"] == %{"TraitMethod" => [trait, 0]})),
         true <- id == f["def_id"],
         p = f["generics"],
         true <- indices(p["regions"]) == [0] and Map.put(p, "regions", []) == params(),
         true <- CallModels.expand(f["signature"]["inputs"], refs) == [range, ref(str)],
         true <- option?(f["signature"]["output"], ref(str), t, refs) do
      model(
        "core::str::traits::{core::slice::index::SliceIndex<core::ops::range::#{kind}<usize>, str, str>}::get",
        operation(kind)
      )
      |> Map.put(:str_range, kind)
    else
      _ -> nil
    end
  end

  defp model(rust, operation) do
    %{
      rust_name: rust,
      lean: "StringSlices." <> operation,
      builtin: false,
      can_fail: true,
      lift: true,
      string_slice_op: operation,
      model_digest: Lynx.Rust.Fingerprint.digest(@contents),
      label:
        "Shared str range-get model preserving byte bounds and UTF-8 boundaries; delegates through the resolved standard SliceIndex dictionary; Rust core raw-pointer implementation and native layout remain unverified"
    }
  end

  # Retain the exact dictionary and implementation identity. A generic wrapper
  # must never turn a user-defined SliceIndex into the standard range operation.
  def index_method!(actual, models, t, refs, traits) do
    with %{
           "regions" => [_],
           "types" => [range, str],
           "const_generics" => [],
           "trait_refs" => [dictionary]
         } <- actual,
         %{
           "kind" => %{"TraitImpl" => %{"id" => impl_id, "generics" => impl_args}},
           "trait_decl_ref" => %{"id" => trait, "generics" => declared}
         } <-
           ResourceModels.dictionary(dictionary, traits),
         true <- CallModels.expand(impl_args, refs) == args([]),
         impl when is_map(impl) <- find(t["trait_impls"], impl_id),
         expected = CallModels.expand(args([range, str, str]), refs),
         true <- CallModels.expand(declared, refs) == expected,
         true <- impl["impl_trait"]["id"] == trait,
         true <- CallModels.expand(impl["impl_trait"]["generics"], refs) == expected,
         [%{"skip_binder" => %{"id" => method}}] <-
           Enum.filter(impl["methods"], &(&1["kind"] == %{"TraitMethod" => [trait, 0]})),
         %{str_range: kind, function: f} <- models[method],
         true <- kind == range_kind(CallModels.expand(range, refs), t, refs),
         true <- get_in(f, ["src", "TraitImpl", "impl_ref", "id"]) == impl_id do
      method
    else
      _ ->
        raise ArgumentError,
              "missing or unsupported SliceIndex implementation selected by str::get"
    end
  end

  def unchecked_from_call!(actual, models, t, refs, traits) do
    get = index_method!(actual, models, t, refs, traits)

    with %{str_range: "RangeFrom"} <- models[get],
         %{"kind" => %{"TraitImpl" => %{"id" => id}}} <-
           ResourceModels.dictionary(hd(actual["trait_refs"]), traits),
         impl when is_map(impl) <- find(t["trait_impls"], id),
         %{"skip_binder" => %{"id" => unchecked}} <- Enum.at(impl["methods"], 2),
         %{elaboration_only: true, function: f} <- models[unchecked],
         true <- f["src"]["TraitImpl"]["item_id"] == 2,
         p = f["generics"],
         true <- p == params(),
         [range, str] <- CallModels.expand(actual["types"], refs),
         true <-
           Map.take(f["signature"], ~w(abi is_unsafe is_variadic)) == %{
             "abi" => "Rust",
             "is_unsafe" => true,
             "is_variadic" => false
           },
         true <-
           CallModels.expand(f["signature"]["inputs"], refs) == [
             range,
             %{"RawPtr" => [str, "Shared"]}
           ],
         true <-
           CallModels.expand(f["signature"]["output"], refs) == %{"RawPtr" => [str, "Shared"]} do
      unchecked
    else
      _ -> raise ArgumentError, "missing or unsupported unchecked RangeFrom string implementation"
    end
  end

  defp range_kind(%{"Adt" => %{"builtin" => nil, "id" => id, "generics" => actual}}, t, refs) do
    with true <- actual == args([usize()]),
         %{
           "src" => "Normal",
           "item_meta" => %{"name" => name},
           "generics" => p,
           "kind" => %{"Struct" => fields}
         } <- find(t["type_decls"], id),
         [
           %{"Ident" => ["core", 0]},
           %{"Ident" => ["ops", 0]},
           %{"Ident" => ["range", 0]},
           %{"Ident" => [kind, 0]}
         ] <- name,
         true <- kind in ~w(Range RangeFrom RangeTo),
         true <- indices(p["types"]) == [0] and Map.put(p, "types", []) == params(),
         expected =
           (case kind do
              "Range" -> ~w(start end)
              "RangeFrom" -> ["start"]
              "RangeTo" -> ["end"]
            end),
         true <-
           Enum.map(fields, &(Map.take(&1, ~w(name ty)) |> CallModels.expand(refs))) ==
             Enum.map(expected, &%{"name" => &1, "ty" => variable(0)}) do
      kind
    else
      _ -> nil
    end
  end

  defp range_kind(_, _, _), do: nil

  defp str?(type, t, refs), do: StringModels.borrowed_type?(ref(type), t, refs)

  defp trait?(id, t) do
    case find(t["trait_decls"], id) do
      %{"src" => "Normal", "is_unsafe" => true, "item_meta" => %{"name" => name}, "generics" => p} ->
        name == path(~w(core slice index SliceIndex)) and indices(p["types"]) == [0, 1, 2] and
          Map.put(p, "types", []) == params()

      _ ->
        false
    end
  end

  defp option?(type, inner, t, refs) do
    case CallModels.expand(type, refs) do
      %{"Adt" => %{"builtin" => nil, "id" => id, "generics" => actual}} ->
        is_map(find(t["type_decls"], id)) and actual == args([inner]) and
          Lynx.Rust.OptionModels.option_type?(find(t["type_decls"], id), refs)

      _ ->
        false
    end
  end

  defp indices(rows) when is_list(rows), do: Enum.map(rows, & &1["index"])
  defp indices(_), do: nil
  defp find(rows, id), do: Enum.find(rows || [], &(&1 && &1["def_id"] == id))
  defp variable(id), do: %{"TypeVar" => %{"Free" => id}}
  defp region, do: %{"Var" => %{"Free" => 0}}
  defp ref(type), do: %{"Ref" => [region(), type, "Shared"]}
  defp usize, do: %{"Scalar" => %{"Integer" => %{"Unsigned" => "Usize"}}}
  defp path(parts), do: Enum.map(parts, &%{"Ident" => [&1, 0]})
  defp args(types), do: ResourceModels.args(types)

  defp params,
    do:
      Map.new(
        ~w(regions types const_generics trait_clauses outlives trait_type_constraints),
        &{&1, []}
      )

  defp operation("Range"), do: "rangeGet"
  defp operation("RangeFrom"), do: "fromGet"
  defp operation("RangeTo"), do: "toGet"

  def scope(audit, prefix) do
    %{
      audit
      | external_calls:
          Map.new(audit.external_calls, fn {id, m} ->
            if m[:string_slice_op],
              do: {id, %{m | lean: prefix <> ".StringSlices." <> m.string_slice_op}},
              else: {id, m}
          end)
    }
  end

  def external_names(calls, prefix) do
    alias_from? = Enum.any?(calls, fn {_, m} -> m[:slice_range_from_checked] end)

    entries =
      for {_, m} <- calls, kind = m[:str_range] do
        range =
          if kind == "RangeFrom" and alias_from?,
            do: "lynx_slice::RangeFrom",
            else: "core::ops::range::" <> kind

        %{
          "rust_pattern" => "core::slice::index::SliceIndex<#{range}<usize>, str, str>",
          "extract_name" => prefix <> ".StringSlices." <> kind <> "Index"
        }
      end

    if entries == [], do: %{}, else: %{"trait_impls" => Enum.uniq(entries)}
  end

  def install!(audit, output, prefix) do
    if Enum.any?(audit.external_calls, fn {_, m} -> m[:string_slice_op] end) do
      module = prefix <> ".StringSlicesModel"
      path = Path.join(output, String.replace(module, ".", "/") <> ".lean")

      case File.read(path) do
        {:ok, @marker <> _} -> :ok
        {:error, :enoent} -> :ok
        _ -> raise ArgumentError, "refusing to overwrite a user string-slice module: #{path}"
      end

      File.mkdir_p!(Path.dirname(path))
      File.write!(path, @marker <> String.replace(@contents, "__PREFIX__", prefix))
      funs = Path.join(output, String.replace(prefix, ".", "/") <> "/Funs.lean")
      contents = File.read!(funs)
      marker = "public import " <> prefix <> ".Types"

      unless String.contains?(contents, marker),
        do: raise(ArgumentError, "missing string-slice Types import")

      File.write!(funs, String.replace(contents, marker, marker <> "\npublic import " <> module))
      [module]
    else
      []
    end
  end
end
