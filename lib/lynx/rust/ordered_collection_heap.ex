defmodule Lynx.Rust.OrderedCollectionHeap do
  @moduledoc false
  @source Path.expand("../../../priv/lean/LynxRustOrderedCollectionHeap.lean", __DIR__)
  @external_resource @source
  @contents File.read!(@source)
  @marker "-- Generated by Lynx: ordered collection heap codecs.\n"

  def install!(audit, output, prefix, execution) do
    if execution == :runtime and audit.ordered_collections.families != [] do
      name = prefix <> ".OrderedCollectionHeap"
      path = Path.join(output, String.replace(name, ".", "/") <> ".lean")

      case File.read(path) do
        {:ok, @marker <> _} -> :ok
        {:error, :enoent} -> :ok
        _ -> raise ArgumentError, "refusing to overwrite a user Lean module: #{path}"
      end

      File.mkdir_p!(Path.dirname(path))

      File.write!(
        path,
        (@marker <> @contents)
        |> String.replace("__PREFIX__", prefix)
        |> String.replace("__RUNTIME__", hd(String.split(prefix, ".")) <> ".NativeRuntime")
      )

      [name]
    else
      []
    end
  end
end
