defmodule Lynx.Rustler.EncoderDisposal do
  @moduledoc false
  alias Lynx.Rust.VTables

  # Only dictionaries whose virtual destructor was already checked may receive
  # a disposal capability. Unknown dictionaries keep the bridge's failing default.
  # This adds metadata to the emitted record; the encode method is left intact.
  def install!(audit, translation, output) do
    audit.constants
    |> Map.values()
    |> Enum.filter(&(get_in(&1, ["lynx_vtable", :external_trait]) == "rustler::types::Encoder"))
    |> Enum.sort_by(& &1["lynx_vtable"].impl)
    |> Enum.map(fn table ->
      linked = VTables.link!(table, translation)
      info = table["lynx_vtable"]
      [impl] = Enum.filter(translation["trait_impls"], &(&1["def_id"] == info.impl))
      expected = info[:model_method] || method!(info, translation)
      name = relative(impl["lean_name"], translation)
      path = Path.join(output, impl["lean_file"])
      source = File.read!(path)

      unless String.starts_with?(source, "-- THIS FILE WAS AUTOMATICALLY GENERATED BY AENEAS"),
        do: raise(ArgumentError, "refusing to decorate a user Encoder dictionary: #{path}")

      pattern =
        Regex.compile!(
          "(def\\s+" <>
            Regex.escape(name) <>
            "\\s*:\\s*Lynx\\.Rustler\\.Encoder\\s+[^{}]+?:=\\s*\\{\\s*encode\\s*:=\\s*)([^{}]+?)(\\s*\\})"
        )

      case Regex.scan(pattern, source) do
        [[whole, prefix, encoded, suffix]] ->
          unless String.trim(encoded) == relative(expected, translation),
            do:
              raise(
                ArgumentError,
                "Encoder disposal cannot replace the audited encode method: #{name}"
              )

          updated =
            prefix <>
              String.trim_trailing(encoded) <>
              ",\n  dispose := fun _ => RustM.ok ()" <> suffix

          File.write!(path, String.replace(source, whole, updated, global: false))

        _ ->
          raise ArgumentError, "missing or inconsistent emitted Encoder dictionary: #{name}"
      end

      %{
        implementation: info.impl,
        dictionary: linked["lean_name"],
        drop_shim: hd(info.shims),
        kind: if(info[:model_method], do: :sdk_string, else: :compiler_noop)
      }
    end)
  end

  defp method!(info, translation) do
    [id] = info.methods

    [method] =
      Enum.filter(translation["functions"], &(&1["def_id"] == id and &1["is_opaque"] == false))

    method["lean_name"]
  end

  defp relative(name, translation),
    do: String.replace_prefix(name, translation["crate"] <> ".", "")
end
