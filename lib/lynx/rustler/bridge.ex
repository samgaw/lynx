defmodule Lynx.Rustler.Bridge do
  @moduledoc false
  @source Path.expand("../../../priv/lean/LynxRustlerBridge.lean", __DIR__)
  @external_resource @source
  @contents File.read!(@source)

  def install!(project, prefix) do
    unless Regex.match?(~r/^[A-Z][A-Za-z0-9_]*(\.[A-Z][A-Za-z0-9_]*)*$/, prefix),
      do: raise(ArgumentError, "invalid generated Lean module prefix: #{inspect(prefix)}")

    # The bridge must belong to an existing Lake library, like the extraction.
    module = (prefix |> String.split(".") |> hd()) <> ".RustlerBridge"
    path = Path.join(project, String.replace(module, ".", "/") <> ".lean")

    case File.read(path) do
      {:ok, @contents} ->
        :ok

      {:ok, "-- Generated by Lynx:" <> _} ->
        File.write!(path, @contents)

      {:ok, _} ->
        raise ArgumentError, "refusing to overwrite a user Lean module: #{path}"

      {:error, :enoent} ->
        File.mkdir_p!(Path.dirname(path))
        File.write!(path, @contents)

      {:error, reason} ->
        raise File.Error, reason: reason, action: "read Rustler bridge", path: path
    end

    module
  end
end
